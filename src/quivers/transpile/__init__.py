type _LazyExport = (
    type
    | types.FunctionType
    | types.GenericAlias
    | TypeAliasType
    | frozenset[str]
    | dict[str, str]
    | dict[str, FamilyMeta]
    | str
)


def __getattr__(name: str) -> _LazyExport:
    """Bind a public name of a leaf module on first access.

    Parameters
    ----------
    name : str
        The attribute requested.

    Returns
    -------
    _LazyExport
        The object the defining module binds under that name.

    Raises
    ------
    AttributeError
        If ``name`` is not a lazily bound export.
    """
    home = _LAZY_EXPORTS.get(name)
    if home is None:
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    value: _LazyExport = getattr(importlib.import_module(home), name)
    globals()[name] = value
    return value


