"""A sufficient finiteness certificate for contiguous lexical span rules."""

from __future__ import annotations

from collections import defaultdict, deque
from dataclasses import dataclass
from graphlib import CycleError, TopologicalSorter

from quivers.qiec.rules import Rule, RulePresentation, _variables
from quivers.qiec.types import IndexConstructor, IndexLiteral, IndexTerm, IndexVariable


@dataclass(frozen=True)
class SpanOrder:
    """Finite endpoint order refined by an acyclic equal-width head graph.

    Parameters
    ----------
    height
        The longest path of width-preserving category transitions.
    unary_height
        The longest path among unary rules alone.
    maximum_arity
        The most premises of any rule in the presentation.
    nullable
        Whether the category approximation contains any empty span.
    """

    height: int
    unary_height: int
    maximum_arity: int
    nullable: bool

    def weight_range_divisor(self, length: int) -> int:
        """Bound arithmetic on any full-span proof and its normalization.

        Positive-width leaves have disjoint interiors of total length at
        most `length`. Suppress nodes with one positive-width child; each
        remaining positive-width node accounts for at most `height + 1`
        nodes before suppression. Each can also have `maximum_arity`
        zero-width children. Their subtrees have depth at most `height`.

        Parameters
        ----------
        length
            The number of tokens in the query's full span.

        Returns
        -------
        int
            A bound on the number of weight terms in a proof, with room
            for combining log masses and subtracting their normalizer.
        """
        if not self.nullable:
            return max(1, 4 * length * (1 + self.height))
        arity = self.maximum_arity
        depth = 1 + self.height
        nullable_size = (arity**depth - 1) // (arity - 1) if arity > 1 else depth
        if length == 0:
            return 2 * nullable_size
        positive_size = (2 * length - 1) * depth
        return 2 * positive_size * (1 + arity * nullable_size)


def _category_head(term: IndexTerm) -> str | None:
    """Identify the head of a category pattern.

    Parameters
    ----------
    term
        The checked category pattern.

    Returns
    -------
    str or None
        A fixed constructor name, or `None` for an unknown head.
    """
    if isinstance(term, IndexConstructor):
        return term.name
    if isinstance(term, IndexLiteral) and isinstance(term.value, str):
        return term.value
    return None


def _literal_position(term: IndexTerm) -> int | None:
    """Read a literal span boundary when it is fixed in the rule.

    Parameters
    ----------
    term
        The checked endpoint pattern.

    Returns
    -------
    int or None
        The boundary when it is a natural literal.
    """
    if isinstance(term, IndexLiteral) and isinstance(term.value, int):
        return term.value
    return None


def _can_have_zero_width(left: IndexTerm, right: IndexTerm) -> bool:
    """Use known unequal endpoints to exclude a zero-width interval.

    Parameters
    ----------
    left, right
        The interval's endpoint patterns.

    Returns
    -------
    bool
        Whether the endpoints could agree in this approximation.
    """
    start, end = _literal_position(left), _literal_position(right)
    return start is None or end is None or start == end


def _check_span(rule: Rule) -> None:
    """Check a rule's endpoint path and generation of every local variable.

    Parameters
    ----------
    rule
        The rule to check, in a presentation with one span judgment.

    Raises
    ------
    ValueError
        If the rule is not a ground interval or a contiguous path with
        all its local variables generated by premises.
    """
    start, end = rule.conclusion.arguments[:2]
    bound = {
        variable.name
        for premise in rule.premises
        for argument in premise.judgment.arguments
        for variable in _variables(argument)
    }
    if any(binder.name not in bound for binder in rule.telescope):
        raise ValueError(
            f"deduction outcome rule {rule.name!r} must bind its entire telescope "
            "through its premises"
        )
    if rule.values:
        raise ValueError(f"deduction outcome rule {rule.name!r} cannot supply values")
    if not rule.premises:
        left, right = _literal_position(start), _literal_position(end)
        if left is None or right is None or not 0 <= left <= right:
            raise ValueError(
                f"deduction outcome ground rule {rule.name!r} requires ordered "
                "literal span endpoints"
            )
        return
    path = [start]
    for premise in rule.premises:
        left, right = premise.judgment.arguments[:2]
        if left != path[-1] or premise.hypotheses:
            break
        path.append(right)
    if (
        len(path) != len(rule.premises) + 1
        or path[-1] != end
        or any(
            not isinstance(position, IndexVariable)
            and _literal_position(position) is None
            for position in path
        )
    ):
        raise ValueError(
            f"deduction outcome rule {rule.name!r} must preserve a unary "
            "span or combine contiguous spans in premise order"
        )


def _nullable_categories(rules: tuple[Rule, ...]) -> set[str | None]:
    """Find heads that may derive an empty span by a finite rule proof.

    The marker `None` in the reachable set says some head is nullable.
    A rule with an unknown conclusion head conservatively marks every
    head in the presentation. Premise patterns with fixed unequal
    endpoints cannot be nullable. We abstract away other equalities
    between patterns, which can only enlarge the set.

    Parameters
    ----------
    rules
        The presentation's verified ordered-span rules.

    Returns
    -------
    set of str or None
        Potentially nullable heads, with `None` when some head is nullable.
    """
    heads = {
        _category_head(judgment.arguments[2])
        for rule in rules
        for judgment in (
            rule.conclusion,
            *(premise.judgment for premise in rule.premises),
        )
    }
    waiting: dict[str | None, list[int]] = defaultdict(list)
    remaining: dict[int, int] = {}
    pending: deque[str | None] = deque()
    seen: set[str | None] = set()
    all_heads_published = False

    def publish(head: str | None) -> None:
        """Make a newly nullable head available to waiting rules.

        Parameters
        ----------
        head
            The conclusion's fixed head, or `None` if it is unknown.
        """
        nonlocal all_heads_published
        if all_heads_published:
            return
        all_heads_published = head is None
        for item in (heads | {None}) if head is None else (head, None):
            if item not in seen:
                seen.add(item)
                pending.append(item)

    for index, rule in enumerate(rules):
        if not all(
            _can_have_zero_width(*judgment.arguments[:2])
            for judgment in (
                rule.conclusion,
                *(premise.judgment for premise in rule.premises),
            )
        ):
            continue
        needs = {
            _category_head(premise.judgment.arguments[2]) for premise in rule.premises
        }
        if not needs:
            publish(_category_head(rule.conclusion.arguments[2]))
            continue
        remaining[index] = len(needs)
        for head in needs:
            waiting[head].append(index)
    while pending:
        for index in waiting[pending.popleft()]:
            remaining[index] -= 1
            if remaining[index] == 0:
                publish(_category_head(rules[index].conclusion.arguments[2]))
    return seen


def certify_span_order(presentation: RulePresentation) -> SpanOrder:
    """Certify finite grounding and strict progress of premise dependencies.

    Contiguity makes all intervals ordered and contained in the enclosing
    interval. Endpoints come only from the input or fixed literals. If an
    edge preserves width, all other premises are nullable. Giving each
    such edge a strictly increasing fixed-head rank establishes the order
    `(width, rank)`. Ground axioms and lexical occurrences are finite, and
    a rule has finitely many bindings over finitely many earlier items.
    Induction proves finite grounding even with growing constructor terms.

    Parameters
    ----------
    presentation
        A checked presentation with one span judgment. The proof ignores
        guards, which only delete edges from the certified supergraph.

    Returns
    -------
    SpanOrder
        The rank bounds and nullable information that certify finiteness.

    Raises
    ------
    ValueError
        If a rule breaks contiguity, or a possible equal-width dependency
        has an unknown head or belongs to a cycle of heads.
    """
    rules = presentation.rules
    for rule in rules:
        _check_span(rule)
    nullable = _nullable_categories(rules)
    predecessors: dict[str, set[str]] = defaultdict(set)
    unary: dict[str, set[str]] = defaultdict(set)
    for rule in rules:
        categories = tuple(
            _category_head(premise.judgment.arguments[2]) for premise in rule.premises
        )
        may_be_zero = tuple(
            head in nullable and _can_have_zero_width(*premise.judgment.arguments[:2])
            for head, premise in zip(categories, rule.premises, strict=True)
        )
        positive = may_be_zero.count(False)
        conclusion = _category_head(rule.conclusion.arguments[2])
        for head, possible_zero in zip(categories, may_be_zero, strict=True):
            if positive > (0 if possible_zero else 1):
                continue
            if head is None or conclusion is None:
                raise ValueError(
                    f"deduction outcome equal-width rule {rule.name!r} needs "
                    "fixed category heads to establish acyclicity"
                )
            predecessors[conclusion].add(head)
            if len(categories) == 1:
                unary[conclusion].add(head)
    rank: dict[str, int] = {}
    unary_rank: dict[str, int] = {}
    try:
        for head in TopologicalSorter(predecessors).static_order():
            rank[head] = 1 + max(
                (rank[prior] for prior in predecessors.get(head, ())), default=-1
            )
            unary_rank[head] = 1 + max(
                (unary_rank[prior] for prior in unary.get(head, ())), default=-1
            )
    except CycleError as error:
        scope = "equal-width" if nullable else "unary"
        raise ValueError(
            f"deduction outcome {scope} category heads must be acyclic"
        ) from error
    return SpanOrder(
        height=max(rank.values(), default=0),
        unary_height=max(unary_rank.values(), default=0),
        maximum_arity=max((len(rule.premises) for rule in rules), default=0),
        nullable=bool(nullable),
    )
