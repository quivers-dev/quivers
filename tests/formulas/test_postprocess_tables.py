def test_cumulative_thresholds_reproduce_category_probabilities(
    frame: pd.DataFrame,
) -> None:
    ordinal = fit(
        "r ~ x", data=frame, family="cumulative", method="svi", num_steps=50, seed=1
    )
    names = ordinal.variables(num_samples=6)
    probabilities = ordinal.posterior_epred(num_samples=6)
    thresholds = torch.stack([names[f"b_Intercept[{k}]"] for k in (1, 2, 3)], dim=-1)
    eta = names["b_x"].unsqueeze(-1) * torch.tensor(
        frame["x"].to_numpy(), dtype=thresholds.dtype
    )
    # P(y <= k) = logistic(threshold_k - eta), brms's cumulative logit.
    cumulative = torch.sigmoid(thresholds.unsqueeze(2) - eta.unsqueeze(-1))
    np.testing.assert_allclose(
        cumulative[..., 0].numpy(), probabilities[..., 0].numpy(), rtol=1e-5, atol=1e-6
    )
    np.testing.assert_allclose(
        (cumulative[..., 1] - cumulative[..., 0]).numpy(),
        probabilities[..., 1].numpy(),
        rtol=1e-5,
        atol=1e-6,
    )


def test_fit_tables_have_brms_layouts(gaussian_fit) -> None:
    summary = gaussian_fit.summary(num_samples=40)
    assert summary.fixed is not None
    assert list(summary.fixed.rows) == ORACLE["gaussian"]["summary"]["fixed"]["rows"]
    assert list(summary.fixed.columns) == [
        "Estimate",
        "Est.Error",
        "l-95% CI",
        "u-95% CI",
    ]
    assert (
        list(summary.random["g"].rows)
        == ORACLE["gaussian"]["summary"]["random"]["g"]["rows"]
    )
    assert (
        list(gaussian_fit.fixef(num_samples=40).rows)
        == ORACLE["gaussian"]["fixef"]["rows"]
    )
    ranef = gaussian_fit.ranef(num_samples=40)["g"]
    assert [list(ranef.rows), list(ranef.components)] == [
        ORACLE["gaussian"]["ranef"]["g"]["dimnames"][0],
        ORACLE["gaussian"]["ranef"]["g"]["dimnames"][2],
    ]
    coef = gaussian_fit.coef(num_samples=40)["g"]
    assert list(coef.components) == ORACLE["gaussian"]["coef"]["g"]["dimnames"][2]
    blocks = gaussian_fit.varcorr(num_samples=40)
    assert set(blocks) == {"g"} and blocks["g"].labels == ("Intercept", "x")
    assert (
        list(gaussian_fit.vcov(num_samples=40).rows)
        == ORACLE["gaussian"]["vcov"]["rows"]
    )
    assert gaussian_fit.nobs() == ORACLE["gaussian"]["nobs"]
    assert gaussian_fit.ngrps() == ORACLE["gaussian"]["ngrps"]
    assert (
        gaussian_fit.ndraws(),
        gaussian_fit.nchains(),
        gaussian_fit.niterations(),
    ) == (
        100,
        1,
        100,
    )
    # Fit tables are the table functions applied to the fit's own named draws.
    names = gaussian_fit.variables(num_samples=40)
    np.testing.assert_array_equal(
        gaussian_fit.fixef(num_samples=40).values.numpy(),
        fixef_table(
            names, probs=(0.025, 0.975), robust=False, pars=None
        ).values.numpy(),
    )


