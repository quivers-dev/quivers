def test_predictions_residuals_and_draw_selection(
    gaussian_fit, frame: pd.DataFrame
) -> None:
    epred = gaussian_fit.posterior_epred(num_samples=30, seed=4)
    fitted = gaussian_fit.fitted(num_samples=30, seed=4)
    np.testing.assert_allclose(
        fitted.values.numpy(),
        posterior_summary(epred).values.numpy(),
        rtol=1e-12,
    )
    errors = gaussian_fit.predictive_error(method="fitted", num_samples=30, seed=4)
    y = torch.tensor(frame["y"].to_numpy(), dtype=torch.float64)
    np.testing.assert_allclose(
        errors.numpy(), (y - epred.to(torch.float64)).numpy(), rtol=1e-12
    )
    residuals = gaussian_fit.residuals(method="posterior_epred", num_samples=30, seed=4)
    np.testing.assert_allclose(
        residuals.values.numpy(), posterior_summary(errors).values.numpy(), rtol=1e-12
    )
    pearson = gaussian_fit.residuals(
        type="pearson", summary=False, num_samples=30, seed=4
    )
    predicted = gaussian_fit.posterior_predict(num_samples=30, seed=4).to(torch.float64)
    scale = predicted.flatten(0, 1).std(dim=0, correction=1)
    np.testing.assert_allclose(
        pearson.numpy(), ((y - predicted) / scale).numpy(), rtol=1e-12
    )
    # draw_ids select pooled draws; linear predictors are deterministic per draw.
    linpred = gaussian_fit.posterior_linpred(num_samples=10, seed=0)
    chosen = gaussian_fit.fitted(
        scale="linear", draw_ids=[1, 4, 7], summary=False, num_samples=10, seed=0
    )
    np.testing.assert_allclose(
        chosen.numpy()[0], linpred.flatten(0, 1)[[1, 4, 7]].numpy(), rtol=1e-6
    )
    sigma = gaussian_fit.fitted(parameter="sigma", summary=False, num_samples=10)
    np.testing.assert_allclose(
        sigma.numpy(),
        gaussian_fit.posterior_linpred(
            parameter="sigma", transform=True, num_samples=10
        ).numpy(),
    )
    new = gaussian_fit.predict(new_data=frame.iloc[:4], num_samples=20)
    assert new.values.shape == (4, 4)
    interval = gaussian_fit.predictive_interval(num_samples=20)
    assert list(interval.columns) == ["5%", "95%"]
    with pytest.raises(ValueError, match="scale"):
        gaussian_fit.fitted(scale="identity")  # type: ignore[arg-type]
    with pytest.raises(ValueError, match="not supported"):
        gaussian_fit.predictive_error(method="posterior_mode")
    with pytest.raises(ValueError, match="draw_ids"):
        gaussian_fit.predict(draw_ids=[0, 0], num_samples=5)


