def test_ranef_and_coef_arrays_match_brms() -> None:
    names = brms_names("gaussian")
    members = level_members(names)
    labels, values = (
        tuple(label for label, _ in members["g"]),
        torch.stack([value for _, value in members["g"]], dim=-1),
    )
    ranef = posterior_summary(
        values, probs=(0.1, 0.9), labels=("a", "b", "c"), components=labels
    )
    oracle = ORACLE["gaussian"]["ranef"]["g"]
    assert [list(ranef.rows), list(ranef.columns), list(ranef.components)] == oracle[
        "dimnames"
    ]
    np.testing.assert_allclose(
        ranef.values.numpy(), array_values(oracle), rtol=TOLERANCE
    )
    fixed = {name[2:]: value for name, value in names.items() if name.startswith("b_")}
    arrays = coef_arrays(fixed, members, threshold_sign="plus")
    coef_labels, coef_values = arrays["g"]
    coef = posterior_summary(
        coef_values, robust=True, labels=("a", "b", "c"), components=coef_labels
    )
    oracle = ORACLE["gaussian"]["coef"]["g"]
    assert list(coef.components) == oracle["dimnames"][2]
    np.testing.assert_allclose(
        coef.values.numpy(), array_values(oracle), rtol=TOLERANCE
    )


def test_cumulative_coef_subtracts_group_intercepts_from_thresholds() -> None:
    names = brms_names("cumulative")
    members = level_members(names)
    fixed = {name[2:]: value for name, value in names.items() if name.startswith("b_")}
    labels, values = coef_arrays(fixed, members, threshold_sign="thres_minus_eta")["g"]
    table = posterior_summary(
        values, robust=True, labels=("a", "b", "c"), components=labels
    )
    oracle = ORACLE["cumulative"]["coef"]["g"]
    assert list(table.components) == oracle["dimnames"][2]
    np.testing.assert_allclose(
        table.values.numpy(), array_values(oracle), rtol=TOLERANCE
    )
    # A wrong sign convention is detected.
    _, wrong = coef_arrays(fixed, members, threshold_sign="plus")["g"]
    wrong_table = posterior_summary(
        wrong, robust=True, labels=("a", "b", "c"), components=labels
    )
    assert not np.allclose(wrong_table.values.numpy(), array_values(oracle))


def test_varcorr_and_vcov_match_brms() -> None:
    names = brms_names("gaussian")
    sd, cor = group_varcorr(names)["g"]
    block = varcorr_block(sd, cor, summary=True, probs=(0.025, 0.975), robust=False)
    oracle = ORACLE["gaussian"]["varcorr"]["g"]
    assert block.sd is not None and block.cor is not None and block.cov is not None
    assert_table(block.sd, oracle["sd"])
    for key, table in (("cor", block.cor), ("cov", block.cov)):
        assert [
            list(table.rows),
            list(table.columns),
            list(table.components),
        ] == oracle[key]["dimnames"]
        np.testing.assert_allclose(
            table.values.numpy(), array_values(oracle[key]), rtol=1e-9, atol=1e-12
        )
    assert_table(
        vcov_table(names, correlation=False, pars=None), ORACLE["gaussian"]["vcov"]
    )
    assert_table(
        vcov_table(names, correlation=True, pars=None), ORACLE["gaussian"]["vcov_cor"]
    )


def test_fit_summary_sections_match_brms() -> None:
    names = brms_names("gaussian")
    summary = fit_summary(
        {n: v for n, v in names.items() if not n.startswith("r_")},
        dpars=frozenset({"sigma"}),
        kind="mcmc",
        algorithm="sampling",
        formula="y ~ x + f + (1 + x | g)",
        family="gaussian(identity)",
        nobs=30,
        ngrps={"g": 3},
        warmup=150,
        divergences=0,
        prob=0.9,
        robust=False,
        mc_se=False,
    )
    oracle = ORACLE["gaussian"]["summary"]
    assert summary.fixed is not None
    # Rhat and ESS reuse quivers's rank-normalized estimators (Vehtari et al.
    # 2021), which follow ArviZ. ArviZ and R's posterior package stop Geyer's
    # initial positive sequence one lag pair apart; where their ESS differ,
    # quivers must equal ArviZ, and elsewhere it must equal brms exactly.
    for ours, theirs, rows in (
        (summary.fixed, oracle["fixed"], [f"b_{r}" for r in oracle["fixed"]["rows"]]),
        (
            summary.random["g"],
            oracle["random"]["g"],
            ["sd_g__Intercept", "sd_g__x", "cor_g__Intercept__x"],
        ),
    ):
        expected = table_values(theirs)
        for i, name in enumerate(rows):
            draws = names[name].numpy()
            for j, method in ((5, "bulk"), (6, "tail")):
                reference = float(
                    az.ess(
                        draws, method=method, prob=0.05 if method == "tail" else None
                    )
                )
                if abs(reference - expected[i, j]) > 1e-9 * expected[i, j]:
                    expected[i, j] = reference
        assert list(ours.rows) == theirs["rows"]
        np.testing.assert_allclose(ours.values.numpy(), expected, rtol=TOLERANCE)
    assert summary.spec_pars is None and summary.chains == 2


def test_rhat_and_neff_ratio_match_brms() -> None:
    names = brms_names("gaussian")
    for name in ("b_Intercept", "b_x", "sd_g__Intercept", "cor_g__Intercept__x"):
        value = names[name]
        assert float(rhat(value)) == pytest.approx(
            ORACLE["gaussian"]["rhat"][name], rel=1e-9
        )
        ratio = min(float(ess(value, method="bulk")), float(ess(value, method="tail")))
        assert ratio / 300 == pytest.approx(
            ORACLE["gaussian"]["neff_ratio"][name], rel=1e-9
        )


