def test_joint_fit_tables(frame: pd.DataFrame) -> None:
    data = frame.assign(y2=frame["y"] * 0.5 + frame["z"])
    joint = fit(
        bf("y ~ x + (1 | g)") + bf("y2 ~ x"),
        data=data,
        method="svi",
        num_steps=100,
        seed=3,
    )
    summary = joint.summary(num_samples=30)
    assert summary.fixed is not None and summary.spec_pars is not None
    assert list(summary.fixed.rows) == ["y_Intercept", "y_x", "y2_Intercept", "y2_x"]
    assert list(summary.spec_pars.rows) == ["sigma_y", "sigma_y2"]
    assert summary.rescor is not None and list(summary.rescor.rows) == ["rescor(y,y2)"]
    assert list(summary.random["g"].rows) == ["sd(y_Intercept)"]
    blocks = joint.varcorr(num_samples=30)
    assert blocks["residual__"].labels == ("y", "y2")
    assert blocks["residual__"].cor is not None
    assert joint.ranef(num_samples=30)["g"].components == ("y_Intercept",)
    assert joint.nobs() == 30 and joint.nobs(resp="y2") == 30
    predictions = joint.predict(num_samples=20)
    assert set(predictions) == {"y", "y2"}
    residuals = joint.residuals(
        resp="y2", method="posterior_epred", summary=False, num_samples=20
    )
    expected = torch.tensor(
        data["y2"].to_numpy(), dtype=torch.float64
    ) - joint.posterior_epred(resp="y2", num_samples=20)["y2"].to(torch.float64)
    np.testing.assert_allclose(residuals["y2"].numpy(), expected.numpy(), rtol=1e-12)


def test_criteria_survive_artifact_round_trip(
    gaussian_fit, tmp_path: pathlib.Path
) -> None:
    stored = gaussian_fit.add_criterion(["waic", "bayes_R2"], num_samples=50)
    assert stored.criterion("waic") is stored.criteria["waic"]
    save_fit(stored, tmp_path / "fit")
    restored = load_fit(tmp_path / "fit")
    assert isinstance(restored, BayesianFit)
    waic = restored.criterion("waic")
    assert waic.elpd == stored.criteria["waic"].elpd
    assert torch.equal(waic.pointwise_elpd, stored.criteria["waic"].pointwise_elpd)
    assert torch.equal(restored.criterion("bayes_R2"), stored.criteria["bayes_R2"])
    with pytest.raises(KeyError, match="add_criterion"):
        gaussian_fit.criterion("loo")


