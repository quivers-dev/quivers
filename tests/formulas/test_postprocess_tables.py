# Float64 summaries of identical numbers: the tolerance is a few ulps of the
# accumulated sums over 300 draws, fixed before comparing.
TOLERANCE = 1e-10


def draws_of(model: str) -> dict[str, torch.Tensor]:
    """Return a model's exported draws as ``(chain, draw)`` tensors.

    Parameters
    ----------
    model : str
        Oracle model key.

    Returns
    -------
    dict[str, torch.Tensor]
        Float64 draws keyed by brms variable name.
    """
    return {
        name: torch.from_numpy(np.asarray(values, dtype=np.float64)).T
        for name, values in ORACLE[model]["draws"].items()
    }


def brms_names(model: str) -> dict[str, torch.Tensor]:
    """Keep brms's documented parameter classes, dropping Stan internals.

    Parameters
    ----------
    model : str
        Oracle model key.

    Returns
    -------
    dict[str, torch.Tensor]
        Draws of ``b_``, ``sd_``, ``cor_``, ``r_<group>[...]`` and family
        parameters in brms's order.
    """
    keep = ("b_", "sd_", "cor_", "r_g[", "sigma", "disc")
    return {
        name: value
        for name, value in draws_of(model).items()
        if name.startswith(keep) and not name.startswith("Intercept")
    }


def table_values(table: dict) -> np.ndarray:
    """Read an oracle matrix with R's missing values as NaN.

    Parameters
    ----------
    table : dict
        Oracle table with ``values``.

    Returns
    -------
    numpy.ndarray
        Float64 matrix.
    """
    return np.array(
        [[math.nan if v == "NA" else v for v in row] for row in table["values"]],
        dtype=np.float64,
    )


def array_values(array: dict) -> np.ndarray:
    """Read an oracle three-way array stored column-major by R.

    Parameters
    ----------
    array : dict
        Oracle array with ``dim`` and ``values``.

    Returns
    -------
    numpy.ndarray
        Array with R's dimensions.
    """
    return np.array(array["values"], dtype=np.float64).reshape(array["dim"], order="F")


def assert_table(ours: SummaryTable, theirs: dict) -> None:
    """Compare a two-way table with a brms table, labels and values.

    Parameters
    ----------
    ours : SummaryTable
        Computed table.
    theirs : dict
        Oracle table.
    """
    rows = theirs["rows"] if isinstance(theirs["rows"], list) else [theirs["rows"]]
    assert list(ours.rows) == rows
    assert list(ours.columns) == theirs["columns"]
    np.testing.assert_allclose(
        ours.values.numpy(), table_values(theirs), rtol=TOLERANCE, atol=TOLERANCE
    )


def level_members(names: dict[str, torch.Tensor]) -> dict[str, list]:
    """Rebuild per-level group coefficients from ``r_g[level,coef]`` names.

    Parameters
    ----------
    names : dict[str, torch.Tensor]
        brms-named draws.

    Returns
    -------
    dict[str, list]
        ``{"g": [(coef, draws (chain, draw, level))]}`` in brms's coef order.
    """
    coefs: dict[str, dict[str, torch.Tensor]] = {}
    for name, value in names.items():
        if name.startswith("r_g["):
            level, coef = name[4:-1].split(",")
            coefs.setdefault(coef, {})[level] = value
    return {
        "g": [
            (coef, torch.stack([levels[level] for level in ("a", "b", "c")], dim=-1))
            for coef, levels in coefs.items()
        ]
    }


def test_posterior_summary_and_interval_match_brms() -> None:
    names = brms_names("gaussian")
    selected = {
        name: names[name]
        for name in ORACLE["gaussian"]["posterior_summary"]["rows"]
        if name in names
    }
    reference = ORACLE["gaussian"]["posterior_summary"]
    keep = [i for i, row in enumerate(reference["rows"]) if row in selected]
    oracle = {
        "rows": [reference["rows"][i] for i in keep],
        "columns": reference["columns"],
        "values": [reference["values"][i] for i in keep],
    }
    assert_table(posterior_summary(selected), oracle)
    interval = ORACLE["gaussian"]["posterior_interval"]
    oracle_interval = {
        "rows": [interval["rows"][i] for i in keep],
        "columns": interval["columns"],
        "values": [interval["values"][i] for i in keep],
    }
    assert_table(posterior_interval(selected, prob=0.8), oracle_interval)


