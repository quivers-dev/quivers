def test_summary_tables_reject_invalid_requests() -> None:
    draws = torch.zeros(2, 5, 3)
    with pytest.raises(ValueError, match="strictly between"):
        posterior_summary(draws, probs=(0.0, 0.5))
    with pytest.raises(TypeError, match="Boolean"):
        posterior_summary(draws, robust=1)  # type: ignore[arg-type]
    with pytest.raises(ValueError, match="one distinct label per row"):
        posterior_summary(draws, labels=("a", "b"))
    with pytest.raises(ValueError, match="chain and draw"):
        posterior_summary(torch.zeros(0, 5, 3))
    with pytest.raises(ValueError, match="outside the levels"):
        posterior_table(torch.full((1, 4, 2), 3.0), levels=["0", "1"])
    with pytest.raises(ValueError, match="strictly inside"):
        posterior_interval({"a": torch.zeros(1, 4)}, prob=1.0)
    with pytest.raises(KeyError):
        posterior_summary(draws).value(7, "Estimate")


