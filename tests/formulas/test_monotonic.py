def test_new_group_levels_use_the_shared_policies():
    fitted = fit(FORMULA, data=_frame(), method="svi", num_steps=2, seed=4)
    fresh = _fresh().assign(g=["new", "a", "other"])
    with pytest.raises(ValueError, match="allow_new_levels"):
        fitted.posterior_epred(new_data=fresh, num_samples=1)
    for policy in ("uncertainty", "gaussian", "old_levels"):
        draws = fitted.posterior_epred(
            new_data=fresh,
            num_samples=2,
            seed=1,
            allow_new_levels=True,
            sample_new_levels=policy,
        )
        assert draws.shape[-1] == 3 and torch.isfinite(draws).all()


def test_population_predictions_are_monotone_in_the_predictor():
    frame = _frame()
    fitted = fit("y ~ mo(x)", data=frame, method="svi", num_steps=20, seed=5)
    grid = pd.DataFrame({"x": [1, 2, 3, 4]})
    linpred = fitted.posterior_linpred(new_data=grid, num_samples=8, seed=2)
    steps = torch.diff(linpred, dim=-1)
    signs = torch.sign(steps.flatten(0, -2))
    # Each draw is monotone: every step shares the sign of bsp.
    assert bool(((signs >= 0).all(-1) | (signs <= 0).all(-1)).all())


