def _program(module):
    """Compile a module to its native monadic program."""
    program = Compiler(module).compile().morphism
    assert isinstance(program, MonadicProgram)
    return program


def _scale(text: str) -> float:
    """Read the scale argument of a canonical prior call."""
    match = re.search(r"scale=([0-9.e-]+)", text)
    assert match is not None
    return float(match.group(1))


def _fit_with(
    method: Literal["svi", "hmc", "nuts"], formula: str, frame: pd.DataFrame, **extra
) -> BayesianFit:
    """Fit with a tiny run of one inference method."""
    if method == "svi":
        return fit(formula, data=frame, method="svi", num_steps=3, seed=2, **extra)
    return fit(
        formula,
        data=frame,
        method=method,
        num_warmup=2,
        num_samples=2,
        num_chains=1,
        seed=2,
        **extra,
    )


def _restored(path: pathlib.Path) -> BayesianFit:
    """Load a saved formula fit."""
    restored = load_fit(path)
    assert isinstance(restored, BayesianFit)
    return restored


# Sums of at most a dozen products of float64 values of order one: the
# assertions use rtol = atol = 1e-12.


def _oracle_frame() -> pd.DataFrame:
    frame = pd.DataFrame(ORACLE["data"])
    frame["xo"] = pd.Categorical(
        frame["xo"], categories=["lo", "mid", "hi", "top", "max"], ordered=True
    )
    frame["xs"] = pd.Categorical(
        frame["xs"], categories=["a", "b", "c", "d"], ordered=True
    )
    return frame


def _cases():
    return [case for case in ORACLE["cases"]]


def _as_list(value):
    return value if isinstance(value, list) else [value]


def _brms_factors(case):
    """brms's Xmo and Jmo, in brms's Xmo order."""
    data = case["data"]
    count = int(data["Imo"])
    widths = _as_list(data["Jmo"])
    return [(np.asarray(data[f"Xmo_{k + 1}"]), int(widths[k])) for k in range(count)]


@pytest.mark.parametrize("case", _cases(), ids=lambda case: case["formula"])
def test_coding_covariates_and_labels_match_brms(case):
    formula = formula_from_data(case["formula"], _oracle_frame())
    terms = formula.monotonic_terms
    factors = [factor for term in terms for factor in term.factors]
    brms = _brms_factors(case)
    assert len(factors) == len(brms) and len(terms) == int(case["data"]["Ksp"])
    for factor, (codes, width) in zip(factors, brms, strict=True):
        assert factor.width == width
        np.testing.assert_array_equal(factor.design.sum(axis=1), codes)
        # Cumulative indicators: ones in exactly the first x_n columns.
        np.testing.assert_array_equal(
            factor.design, (np.arange(width)[None, :] < codes[:, None]).astype(float)
        )
    covariates = [term.covariate for term in terms if term.column >= 0]
    expected = [
        np.asarray(case["data"][key])
        for key in sorted(
            (key for key in case["data"] if key.startswith("Csp_")),
            key=lambda key: int(key.split("_")[1]),
        )
    ]
    assert len(covariates) == len(expected)
    for actual, oracle in zip(covariates, expected, strict=True):
        np.testing.assert_allclose(actual, oracle, rtol=1e-12, atol=1e-12)
    assert {term.coef for term in terms} <= set(_as_list(case["b"]))
    assert {factor.simplex for factor in factors} == set(_as_list(case["simo"]))


def test_integer_coding_is_relative_to_the_training_minimum_as_in_brms():
    # A deliberately wrong coding (raw values) disagrees with brms's Xmo.
    case = next(c for c in ORACLE["cases"] if c["formula"] == "y ~ mo(x)")
    raw = _oracle_frame()["x"].to_numpy()
    assert not np.array_equal(raw, np.asarray(case["data"]["Xmo_1"]))
    np.testing.assert_array_equal(raw - raw.min(), case["data"]["Xmo_1"])


_TERM = re.compile(
    r"\(bsp\[(\d+)\](?: \+ r_\d+_\d+\[J_\d+\[n\]\])?\)((?: \* mo\(simo_\d+, Xmo_\d+\[n\]\))+)"
    r"((?: \* Csp_\d+\[n\])?)"
)


def _brms_predictor(case, simplexes, bsp):
    """Evaluate brms's generated Stan expression with brms's own data."""
    data = case["data"]
    shared = {
        int(target): int(source)
        for target, source in re.findall(
            r"simo_(\d+) = simo_(\d+);", " ".join(_as_list(case["shared"]))
        )
    }
    line = case["predictor"]
    rows = len(ORACLE["data"])
    mu = np.zeros(rows)
    for coefficient, factors, covariate in _TERM.findall(line):
        value = np.full(rows, bsp[int(coefficient) - 1])
        for simplex, column in re.findall(r"mo\(simo_(\d+), Xmo_(\d+)\[n\]\)", factors):
            zeta = simplexes[shared.get(int(simplex), int(simplex))]
            codes = np.asarray(data[f"Xmo_{column}"], dtype=int)
            # brms: mo(scale, i) = rows(scale) * sum(scale[1:i]), zero at i = 0.
            value = value * np.array([len(zeta) * zeta[:code].sum() for code in codes])
        if covariate:
            index = covariate.rsplit("_", 1)[1].split("[", 1)[0]
            value = value * np.asarray(data[f"Csp_{index}"])
        mu += value
    return mu


@pytest.mark.parametrize("case", _cases(), ids=lambda case: case["formula"])
def test_emitted_predictor_equals_brms_generated_stan_expression(case):
    formula = formula_from_data(case["formula"], _oracle_frame())
    lens = FormulaToQVRModule(families["gaussian"])
    module, _ = lens.forward(formula)
    program = _program(module)
    values = dict(lens.fixed_column_observations(formula))
    values["y"] = torch.as_tensor(formula.response_values.copy())
    brms = _brms_factors(case)
    generator = np.random.default_rng(3)
    simplexes = {
        k + 1: generator.dirichlet(np.ones(width)) for k, (_, width) in enumerate(brms)
    }
    bsp = generator.normal(size=int(case["data"]["Ksp"]))
    # Map brms's simo_k and bsp[k] onto the emitted sites in brms's order.
    factors = [
        (term, factor) for term in formula.monotonic_terms for factor in term.factors
    ]
    for k, (_, factor) in enumerate(factors):
        site = "simo_" + _qvr_name(factor.simplex)
        values.setdefault(site, torch.as_tensor(simplexes[k + 1]))
    for k, term in enumerate(formula.monotonic_terms):
        values["bsp_" + _qvr_name(term.name)] = torch.tensor(
            bsp[k], dtype=torch.float64
        )
    for column in formula.fixed_columns:
        site = "intercept" if column.is_intercept else "beta_" + column.qvr_name
        values[site] = torch.tensor(0.0, dtype=torch.float64)
    for term in formula.random_terms:
        values[f"z_{term.group}_{_qvr_name(term.slope)}"] = torch.zeros(
            3, dtype=torch.float64
        )
    for group, codes in formula.group_indices.items():
        values[f"{group}_idx"] = torch.tensor(codes, dtype=torch.long)
    values["sigma"] = torch.tensor(1.0, dtype=torch.float64)
    result = trace(program, torch.zeros(1, 1), values)
    eta = result.sites["eta"].value.reshape(-1)
    expected = _brms_predictor(case, simplexes, bsp)
    np.testing.assert_allclose(eta.detach().numpy(), expected, rtol=1e-12, atol=1e-12)


def test_joint_density_and_derivatives_match_hand_written_oracle():
    frame = _oracle_frame()
    formula = formula_from_data("y ~ mo(x) * z", frame)
    lens = FormulaToQVRModule(families["gaussian"])
    module, _ = lens.forward(formula)
    program = _program(module)
    observed = lens.fixed_column_observations(formula)
    observed["y"] = torch.as_tensor(formula.response_values.copy())
    priors = get_prior("y ~ mo(x) * z", data=frame)
    scales = {
        site: _scale(text)
        for site, text in priors.items()
        if site.startswith(("bsp_", "beta_"))
    }
    x = torch.tensor(frame["x"].to_numpy(dtype=float) - 1.0)
    z = torch.tensor(frame["z"].to_numpy(dtype=float))
    y = observed["y"]

    def split(point):
        return (
            point[0],
            point[1],
            point[2:5],
            point[5:8],
            point[8],
            point[9],
            point[10],
        )

    def actual(point):
        intercept, beta_z, simo_1, simo_2, bsp_1, bsp_2, sigma = split(point)
        values = {
            **observed,
            "intercept": intercept,
            "beta_z": beta_z,
            "simo_mox1": simo_1,
            "simo_mox_z1": simo_2,
            "bsp_mo_x": bsp_1,
            "bsp_mo_x_z": bsp_2,
            "sigma": sigma,
        }
        joint = trace(program, point.new_zeros(1, 1), values).log_joint
        assert joint is not None
        return joint.sum()

    def oracle(point):
        intercept, beta_z, simo_1, simo_2, bsp_1, bsp_2, sigma = split(point)

        def mo(simo):
            # Bürkner and Charpentier (2020): D * sum_{i <= x} zeta_i.
            partial = torch.cat((point.new_zeros(1), torch.cumsum(simo, 0)))
            return 3.0 * partial[x.long()]

        mu = intercept + beta_z * z + bsp_1 * mo(simo_1) + bsp_2 * mo(simo_2) * z
        normal = torch.distributions.Normal
        flat = torch.distributions.Dirichlet(point.new_ones(3))
        return (
            normal(0.0, 5.0).log_prob(intercept)
            + normal(0.0, scales["beta_z"]).log_prob(beta_z)
            + flat.log_prob(simo_1)
            + flat.log_prob(simo_2)
            + normal(0.0, scales["bsp_mo_x"]).log_prob(bsp_1)
            + normal(0.0, scales["bsp_mo_x_z"]).log_prob(bsp_2)
            + torch.distributions.HalfCauchy(2.0).log_prob(sigma)
            + normal(mu, sigma).log_prob(y).sum()
        )

    point = torch.tensor(
        [0.2, -0.3, 0.2, 0.5, 0.3, 0.6, 0.1, 0.3, 0.7, -0.4, 1.3],
        dtype=torch.float64,
        requires_grad=True,
    )
    torch.testing.assert_close(actual(point), oracle(point))
    torch.testing.assert_close(
        torch.autograd.functional.jacobian(actual, point),
        torch.autograd.functional.jacobian(oracle, point),
    )
    torch.testing.assert_close(
        torch.autograd.functional.hessian(actual, point),
        torch.autograd.functional.hessian(oracle, point),
    )


def test_prior_catalogue_uses_brms_classes_and_expands_scalar_dirichlet():
    frame = _oracle_frame()
    priors = get_prior("y ~ mo(x) * z", data=frame)
    assert priors["simo_mox1"] == "Dirichlet(concentration=[1.0, 1.0, 1.0])"
    assert priors["simo_mox_z1"] == "Dirichlet(concentration=[1.0, 1.0, 1.0])"
    assert {"bsp_mo_x", "bsp_mo_x_z"} <= priors.keys()
    selected = get_prior(
        "y ~ mo(x) * z",
        data=frame,
        priors=[
            PriorSpec(distribution="Dirichlet(2.0)", class_="simo", coef="mox1"),
            PriorSpec(distribution="Normal(0.0, 1.0)", class_="b", coef="mo(x):z"),
        ],
    )
    assert selected["simo_mox1"] == "Dirichlet(concentration=[2.0, 2.0, 2.0])"
    assert selected["simo_mox_z1"] == "Dirichlet(concentration=[1.0, 1.0, 1.0])"
    assert selected["bsp_mo_x_z"] == "Normal(loc=0.0, scale=1.0)"
    shared = get_prior("y ~ mo(x, id='i') * z", data=frame)
    assert [site for site in shared if site.startswith("simo_")] == ["simo_i"]
    vector = get_prior(
        "y ~ mo(x)",
        data=frame,
        priors=PriorSpec(distribution="Dirichlet([1.0, 2.0, 3.0])", class_="simo"),
    )
    assert vector["simo_mox1"] == "Dirichlet(concentration=[1.0, 2.0, 3.0])"


def test_invalid_predictors_priors_and_specifications_are_refused():
    frame = _oracle_frame()
    with pytest.raises(ValueError, match="must be integers or ordered factors"):
        formula_from_data("y ~ mo(z)", frame)
    with pytest.raises(ValueError, match="must be integers or ordered factors"):
        formula_from_data("y ~ mo(f)", frame)
    with pytest.raises(ValueError, match="at least two categories"):
        formula_from_data("y ~ mo(c)", frame.assign(c=2))
    # As in brms, a row with a missing predictor value is dropped.
    dropped = formula_from_data(
        "y ~ mo(m)", frame.assign(m=[np.nan, *frame["x"].iloc[1:].tolist()])
    )
    assert dropped.response_values.shape == (len(frame) - 1,)
    with pytest.raises(ValueError, match="requires the same population-level term"):
        formula_from_data("y ~ z + (mo(x) | g)", frame)
    with pytest.raises(ValueError, match="mo\\(\\) must be a whole term"):
        formula_from_data("y ~ log(mo(x))", frame)
    with pytest.raises(ValueError, match="reserved"):
        formula_from_data("y ~ x", frame, extra_namespace={"mo": abs})
    with pytest.raises(ValueError, match="same number of categories"):
        formula_from = formula_from_data("y ~ mo(x, id='i') + mo(x2, id='i')", frame)
        FormulaToQVRModule(families["gaussian"]).forward(formula_from)
    with pytest.raises(ValueError, match="must be a Dirichlet"):
        get_prior(
            "y ~ mo(x)",
            data=frame,
            priors=PriorSpec(distribution="Normal(0.0, 1.0)", class_="simo"),
        )
    with pytest.raises(ValueError, match="length 3"):
        get_prior(
            "y ~ mo(x)",
            data=frame,
            priors=PriorSpec(distribution="Dirichlet([1.0, 1.0])", class_="simo"),
        )
    # A categorical response gives every free category its own simplex.
    categorical = fit(
        "f ~ mo(x)", data=frame, family="categorical", method="svi", num_steps=1
    )
    assert sum("_simo_" in name for name in categorical.draws()) == 2


def _frame(rows: int = 36) -> pd.DataFrame:
    generator = np.random.default_rng(11)
    frame = pd.DataFrame(
        {
            "x": np.tile(np.arange(1, 5), rows // 4),
            "z": generator.normal(size=rows),
            "g": np.array(["a", "b", "c"])[np.arange(rows) % 3],
        }
    )
    frame["xo"] = pd.Categorical(
        np.array(["low", "mid", "high"])[np.arange(rows) % 3],
        categories=["low", "mid", "high"],
        ordered=True,
    )
    steps = np.array([0.0, 1.0, 1.4, 1.5])
    frame["y"] = (
        steps[frame["x"] - 1]
        + 0.3 * frame["z"]
        + generator.normal(scale=0.3, size=rows)
    )
    return frame


FORMULA = "y ~ mo(x) * z + mo(xo) + (1 + mo(x) | g)"


def _fresh() -> pd.DataFrame:
    return pd.DataFrame(
        {
            "x": [4, 1, 2],
            "z": [0.3, -1.0, 0.0],
            "g": ["b", "a", "c"],
            "xo": pd.Categorical(["high", "low", "mid"], ordered=True),
        }
    )


@pytest.mark.parametrize("method", ["svi", "hmc", "nuts"])
def test_every_inference_method_predicts_fresh_rows(method):
    fitted = _fit_with(method, FORMULA, _frame())
    fresh = _fresh()
    for draws in (
        fitted.posterior_linpred(new_data=fresh, num_samples=2, seed=5),
        fitted.posterior_epred(new_data=fresh, num_samples=2, seed=5),
        fitted.posterior_predict(new_data=fresh, num_samples=2, seed=5),
        *fitted.log_likelihood(
            new_data=fresh.assign(y=[1.5, 0.0, 1.0]), num_samples=2, seed=5
        ).values(),
    ):
        assert draws.shape[-1] == 3 and torch.isfinite(draws).all()
    simplexes = fitted.draws(num_samples=4, seed=1)["simo_mox1"]
    torch.testing.assert_close(
        simplexes.sum(-1), torch.ones(simplexes.shape[:-1], dtype=simplexes.dtype)
    )
    assert bool((simplexes >= 0).all())


def test_fresh_values_outside_the_training_categories_are_refused():
    fitted = fit(FORMULA, data=_frame(), method="svi", num_steps=1, seed=3)
