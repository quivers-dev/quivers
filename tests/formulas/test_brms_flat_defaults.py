"""brms's flat defaults for ARMA, mo(), me() and mi() terms, and R rounding.

The oracle is ``tests/formulas/oracles/brms_default_priors.json`` (cases
``arma_conditional``, ``ar_covariance``, ``monotonic``,
``measurement_error``, ``missing_predictor`` and ``rounding_grid``),
generated by ``brms_default_priors.R`` beside it. brms 2.23.0 keeps these
defaults (R/priors.R ``prior_ac``, ``prior_Xme`` at cran/brms@b124949).
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Literal, cast

import numpy as np
import pandas as pd
import pytest
import torch

from quivers.formulas import BayesianFit, PriorSpec, bf, fit
from quivers.formulas._joint_options import FormulaFitOptions
from quivers.formulas._multivariate import MultivariateFormula
from quivers.formulas._brms_priors import r_round
from quivers.formulas._prior_tables import PriorTable, default_prior
from quivers.inference import MCMCResult
from quivers.inference.trace import trace
from quivers.modeling import load_fit, save_fit

ORACLE = json.loads(
    (Path(__file__).parent / "oracles" / "brms_default_priors.json").read_text()
)
FRAME = pd.DataFrame(ORACLE["data"])
FRAME["xo"] = pd.Categorical(FRAME["xo"].astype(int), ordered=True)
BRMS = {c["name"]: c["table"] for c in ORACLE["cases"]}
TINY = FormulaFitOptions(num_warmup=20, num_samples=6, num_chains=1, seed=3)


def _brms_rows(case: str, klass: str, resp: str = "") -> list[dict]:
    return [
        row
        for row in BRMS[case]
        if row["class"] == klass and row["resp"] == resp and row["coef"] == ""
    ]


def _rows(table: PriorTable, klass: str, resp: str | None = None):
    rows = [
        row
        for row in table.rows
        if row.class_ == klass and (resp is None or row.response == resp)
    ]
    assert rows, (klass, resp)
    return rows


def test_r_round_matches_r_on_halves():
    grid = ORACLE["rounding_grid"]
    for value, rounded in zip(grid["values"], grid["rounded"], strict=True):
        assert r_round(float(value)) == float(rounded), value
    # Python's round differs from R's here, so the port is not vacuous.
    assert round(0.45, 1) == 0.5 and r_round(0.45) == 0.4


def test_conditional_arma_coefficients_take_brms_flat_prior():
    formula = "y ~ x + arma(time = t, p = 1, q = 1)"
    for klass in ("ar", "ma"):
        (brms,) = _brms_rows("arma_conditional", klass)
        assert (brms["prior"], brms["lb"], brms["ub"]) == ("", "", "")
    table = default_prior(formula, data=FRAME, default_priors="brms")
    for klass in ("ar", "ma"):
        for row in _rows(table, klass):
            assert row.prior == "flat" and row.lower is None and row.upper is None
    quivers = default_prior(formula, data=FRAME)
    for klass in ("ar", "ma"):
        assert all(row.prior.startswith("Normal") for row in _rows(quivers, klass))


def test_covariance_ar_coefficient_is_flat_on_its_bounds():
    (brms,) = _brms_rows("ar_covariance", "ar")
    assert (brms["prior"], brms["lb"], brms["ub"]) == ("", "-1", "1")
    table = default_prior(
        "y ~ x + ar(time = t, p = 1, cov = TRUE)", data=FRAME, default_priors="brms"
    )
    for row in _rows(table, "ar"):
        assert "Uniform(low=-1.0, high=1.0)" in row.prior
        assert (row.lower, row.upper) == (-1.0, 1.0)


def test_monotonic_coefficient_is_flat_and_simplex_dirichlet_one():
    assert all(row["prior"] == "" for row in BRMS["monotonic"] if row["class"] == "b")
    (simo,) = [row for row in BRMS["monotonic"] if row["class"] == "simo"]
    assert simo["prior"] == "dirichlet(1)"
    table = default_prior("y ~ mo(xo)", data=FRAME, default_priors="brms")
    assert all(row.prior == "flat" for row in _rows(table, "b"))
    for row in _rows(table, "simo"):
        assert row.prior == "Dirichlet(concentration=[1.0, 1.0])"


def test_measurement_error_hyperparameters_take_brms_flat_priors():
    brms = {(r["class"], r["coef"]): r for r in BRMS["measurement_error"]}
    assert (brms[("meanme", "mex")]["prior"], brms[("meanme", "mex")]["lb"]) == (
        "",
        "",
    )
    assert brms[("sdme", "")]["lb"] == "0" and brms[("sdme", "mex")]["prior"] == ""
    spec = cast(MultivariateFormula, bf("y ~ me(x, sdx)"))
    table = default_prior(spec, data=FRAME, default_priors="brms")
    for row in _rows(table, "meanme"):
        assert row.prior == "flat" and row.lower is None
    for row in _rows(table, "sdme"):
        assert row.prior == "flat on (0, inf)" and row.lower == 0.0
    assert all(row.prior == "flat" for row in _rows(table, "b"))
    quivers = default_prior(spec, data=FRAME)
    assert all(row.prior.startswith("Normal") for row in _rows(quivers, "meanme"))
    assert all(row.prior.startswith("HalfNormal") for row in _rows(quivers, "sdme"))


def test_missing_value_terms_follow_brms_per_response():
    spec = cast(MultivariateFormula, bf("y ~ mi(xm)") + bf("xm | mi() ~ z"))
    table = default_prior(spec, data=FRAME, default_priors="brms")
    for resp in ("y", "xm"):
        assert all(row.prior == "flat" for row in _rows(table, "b", resp))
        (intercept,) = _brms_rows("missing_predictor", "Intercept", resp)
        (sigma,) = _brms_rows("missing_predictor", "sigma", resp)
        location = float(intercept["prior"].split(",")[1])
        (row,) = _rows(table, "Intercept", resp)
        assert row.prior == f"StudentT(df=3.0, loc={location}, scale=2.5)"
        (row,) = _rows(table, "sigma", resp)
        assert sigma["prior"] == "student_t(3, 0, 2.5)"
        assert row.prior == "HalfStudentT(df=3.0, scale=2.5)"


def _log_joint(fitted, values: dict[str, torch.Tensor]) -> torch.Tensor:
    draws = fitted.draws(num_samples=1)
    sites = {name: values.get(name, value[0, 0][None]) for name, value in draws.items()}
    recorded = trace(
        fitted.program, torch.zeros(1, 1), {**fitted.observations, **sites}
    )
    return recorded.log_joint.sum()


def test_flat_arma_prior_scores_zero_against_an_explicit_normal():
    formula = "y ~ x + arma(time = t, p = 1, q = 1)"
    options = {"data": FRAME, "default_priors": "brms", "method": "svi"}
    flat = fit(formula, num_steps=1, **options)
    normal = fit(
        formula,
        num_steps=1,
        priors=PriorSpec(distribution="Normal(0.0, 1.0)", class_="ar")
        + PriorSpec(distribution="Normal(0.0, 1.0)", class_="ma"),
        **options,
    )
    ar = torch.tensor([0.3], requires_grad=True)
    ma = torch.tensor([-0.2], requires_grad=True)
    sites = {"ar_1": ar, "ma_1": ma}
    difference = _log_joint(flat, sites) - _log_joint(normal, sites)
    expected = -(
        torch.distributions.Normal(0.0, 1.0).log_prob(ar)
        + torch.distributions.Normal(0.0, 1.0).log_prob(ma)
    ).sum()
    torch.testing.assert_close(difference, expected, atol=1e-5, rtol=1e-6)
    gradient = torch.autograd.grad(difference, (ar, ma))
    torch.testing.assert_close(gradient[0], ar.detach(), atol=1e-5, rtol=1e-5)
    torch.testing.assert_close(gradient[1], ma.detach(), atol=1e-5, rtol=1e-5)


@pytest.mark.parametrize("method", ["svi", "hmc", "nuts"])
def test_flat_arma_fits_predicts_refits_and_round_trips(
    method: Literal["svi", "hmc", "nuts"], tmp_path: Path
):
    budget: FormulaFitOptions = {"num_steps": 20} if method == "svi" else TINY
    fitted = fit(
        "y ~ x + arma(time = t, p = 1, q = 1)",
        data=FRAME,
        default_priors="brms",
        method=method,
        **budget,
    )
    assert fitted.posterior_linpred(num_samples=4).shape[-1] == len(FRAME)
    with pytest.raises(ValueError, match="improper flat prior"):
        fitted.prior_draws(num_samples=2)
    if method == "nuts":
        assert isinstance(fitted.posterior, MCMCResult)
        path = tmp_path / "arma.qvrfit"
        save_fit(fitted, path)
        restored = load_fit(path)
        assert isinstance(restored, BayesianFit)
        assert torch.equal(restored.draws()["ar_1"], fitted.draws()["ar_1"])
        refit = fitted.update(data=FRAME.iloc[:18])
        assert refit.draws()["ar_1"].shape == (1, 6)


def test_flat_measurement_error_model_fits_and_refuses_prior_draws():
    fitted = fit(
        cast(MultivariateFormula, bf("y ~ me(x, sdx)")),
        data=FRAME,
        default_priors="brms",
        num_warmup=20,
        num_samples=6,
        num_chains=1,
        seed=3,
    )
    names = set(fitted.draws())
    assert {"me_y__x__mean", "me_y__x__sd"} <= names
    assert math.isfinite(float(fitted.draws()["me_y__x__sd"].min()))
    with pytest.raises(ValueError, match="improper flat prior"):
        fitted.prior_draws(num_samples=2)
    assert np.isfinite(
        fitted.posterior_epred(new_data=FRAME.iloc[:3])["y"].numpy()
    ).all()
