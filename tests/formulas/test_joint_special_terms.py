"""``mo()`` and ``mm()`` inside a joint multivariate model, against brms.

The oracle ``oracles/brms_joint_special.json`` is generated by
``oracles/brms_joint_special.R`` from brms's ``make_standata`` and
``make_stancode`` for ``bf(y1 ~ mo(x) * z) + bf(y2 ~ z + (1 | mm(g1, g2,
weights = cbind(w1, w2))))``.
"""

import json
import pathlib
import re

import numpy as np
import pandas as pd
import torch

from quivers.formulas import MultivariateFormula, bf, fit
from quivers.formulas._joint_fit import MultivariateFit
from quivers.inference.trace import trace

ORACLE = json.loads(
    (pathlib.Path(__file__).parent / "oracles" / "brms_joint_special.json").read_text()
)
DATA = ORACLE["standata"]


def _fit() -> MultivariateFit:
    specification = bf("y1 ~ mo(x) * z") + bf(
        "y2 ~ z + (1 | mm(g1, g2, weights = cbind(w1, w2)))"
    )
    assert isinstance(specification, MultivariateFormula)
    fitted = fit(
        specification, data=pd.DataFrame(ORACLE["data"]), method="svi", num_steps=1
    )
    assert isinstance(fitted, MultivariateFit)
    return fitted


def test_response_designs_match_brms_suffixed_data():
    fitted = _fit()
    mono = fitted.emission.responses["y1"].formula
    factors = [factor for term in mono.monotonic_terms for factor in term.factors]
    for k, factor in enumerate(factors):
        np.testing.assert_array_equal(
            factor.design.sum(axis=1), DATA[f"Xmo_y1_{k + 1}"]
        )
    assert [factor.simplex for factor in factors] == ["mox1", "mox:z1"]
    assert set(ORACLE["simo"]) == {"mox1", "mox:z1"}
    covariate = next(term for term in mono.monotonic_terms if term.column >= 0)
    np.testing.assert_allclose(covariate.covariate, DATA["Csp_y1_1"], rtol=0, atol=0)
    member = fitted.emission.responses["y2"].formula
    [membership] = member.grouping.memberships
    for k in range(2):
        np.testing.assert_array_equal(
            np.asarray(membership.codes[k]) + 1, DATA[f"J_1_y2_{k + 1}"]
        )
        np.testing.assert_allclose(
            membership.weights[:, k], DATA[f"W_1_y2_{k + 1}"], rtol=1e-15, atol=0
        )


def test_joint_linear_predictors_equal_brms_generated_stan_expressions():
    fitted = _fit()
    generator = np.random.default_rng(9)
    simplexes = [generator.dirichlet(np.ones(3)) for _ in range(2)]
    bsp = generator.normal(size=2)
    effects = generator.normal(size=int(DATA["N_1"]))
    values = dict(fitted.observations)
    values.update(
        {
            "response_y1__simo_mox1": torch.as_tensor(simplexes[0]),
            "response_y1__simo_mox_z1": torch.as_tensor(simplexes[1]),
            "response_y1__bsp_mo_x": torch.tensor(bsp[0], dtype=torch.float64),
            "response_y1__bsp_mo_x_z": torch.tensor(bsp[1], dtype=torch.float64),
            "response_y2__sigma_mmg1g2_Intercept": torch.tensor(
                1.0, dtype=torch.float64
            ),
            "response_y2__z_mmg1g2_Intercept": torch.as_tensor(effects),
        }
    )
    for name in ("intercept", "beta_z"):
        for response in ("y1", "y2"):
            values[f"response_{response}__{name}"] = torch.tensor(
                0.0, dtype=torch.float64
            )
    sites = trace(fitted.program, torch.zeros(1, 1), values).sites

    def mo(simplex, codes):
        # brms: mo(scale, i) = rows(scale) * sum(scale[1:i]).
        return np.array([len(simplex) * simplex[:code].sum() for code in codes])

    xmo = [np.asarray(DATA[f"Xmo_y1_{k}"], dtype=int) for k in (1, 2)]
    line = ORACLE["predictor"][0]
    assert re.search(
        r"bsp_y1\[2\]\) \* mo\(simo_y1_2, Xmo_y1_2\[n\]\) \* Csp_y1_1", line
    )
    expected_y1 = bsp[0] * mo(simplexes[0], xmo[0]) + bsp[1] * mo(
        simplexes[1], xmo[1]
    ) * np.asarray(DATA["Csp_y1_1"])
    expected_y2 = sum(
        np.asarray(DATA[f"W_1_y2_{k}"])
        * effects[np.asarray(DATA[f"J_1_y2_{k}"], dtype=int) - 1]
        * np.asarray(DATA[f"Z_1_y2_1_{k}"])
        for k in (1, 2)
    )
    for name, expected in (
        ("response_y1__eta", expected_y1),
        ("response_y2__eta", expected_y2),
    ):
        np.testing.assert_allclose(
            sites[name].value.reshape(-1).detach().numpy(),
            expected,
            rtol=1e-12,
            atol=1e-12,
        )


def test_joint_fit_predicts_fresh_rows_with_new_members():
    fitted = _fit()
    fresh = pd.DataFrame(ORACLE["data"]).iloc[:3].assign(g2=["e", "new", "a"])
    draws = fitted.posterior_epred(
        new_data=fresh, num_samples=2, seed=1, allow_new_levels=True
    )
    values = (
        draws if isinstance(draws, torch.Tensor) else torch.stack(list(draws.values()))
    )
    assert torch.isfinite(values).all()
