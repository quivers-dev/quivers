def test_integer_categorical_response_uses_its_sorted_values() -> None:
    """A categorical response takes its sorted distinct values, as brms's ``ncat``."""
    for response in ("y14", "y245"):
        model = fit(
            f"{response} ~ x", data=_ordinal_frame(), family="categorical", **SVI
        )
        assert (
            len(model.category_labels)
            == ORACLE["ordinal"][f"{response}_categorical"]["ncat"]
        )
    assert model.category_labels == (2, 4, 5)


def test_zero_based_codes_keep_their_meaning_and_new_rows_are_checked() -> None:
    """Codes 0..K-1 stay zero-based; new rows must hold a fitted category."""
    frame = _ordinal_frame()
    assert "error" in ORACLE["ordinal"]["y03_cumulative"]
    legacy = fit("y03 ~ x", data=frame, family="cumulative", **SVI)
    assert legacy.category_labels == (0, 1, 2, 3)
    assert legacy.formula.response_layout.category_values == ()
    model = fit("y14 ~ x", data=frame, family="cumulative", **SVI)
    scored = model.log_likelihood(new_data=frame.iloc[:5], num_samples=2)
    assert tuple(scored["y14"].shape) == (1, 2, 5)
    with pytest.raises(
        ValueError, match=r"integers among the categories \[1, 2, 3, 4\]"
    ):
        model.log_likelihood(new_data=frame.iloc[:5].assign(y14=5), num_samples=2)


def test_refit_keeps_the_category_coding_of_the_original_rows() -> None:
    """A refit on rows without a zero still reads a zero-based response as such."""
    frame = _ordinal_frame()
    legacy = fit("y03 | thres(3) ~ x", data=frame, family="cumulative", **SVI)
    subset = frame[frame.y03 > 0]
    assert legacy.update(subset).category_labels == legacy.category_labels
    # A fresh fit of the same rows reads them as brms does: 1, ..., 4.
    fresh = fit("y03 | thres(3) ~ x", data=subset, family="cumulative", **SVI)
    assert fresh.category_labels == (1, 2, 3, 4)


def test_integer_category_values_rules() -> None:
    """The coding rules hold on their own, including what is left unchanged."""
    assert integer_category_values(np.array([2, 4, 5]), "ordinal") == (1, 2, 3, 4, 5)
    assert integer_category_values(np.array([1.0, 2.0]), "ordinal") == (1, 2)
    assert integer_category_values(np.array([0, 1, 2]), "ordinal") == ()
    assert integer_category_values(np.array([1.5, 2.0]), "ordinal") == ()
    assert integer_category_values(np.array([1, 4]), "hurdle") == (0, 1, 2, 3, 4)
    assert integer_category_values(np.array([0, 1, 2]), "nominal") == ()
    assert integer_category_values(np.array([3, 7]), "nominal") == (3, 7)
    assert integer_category_values(np.array([1, 2]), "ordinal", 4) == (1, 2, 3, 4, 5)
    np.testing.assert_array_equal(
        category_positions(np.array([7, 3, 7]), (3, 7)), [1, 0, 1]
    )
    with pytest.raises(ValueError, match="integers among the categories"):
        category_positions(np.array([4]), (3, 7))


