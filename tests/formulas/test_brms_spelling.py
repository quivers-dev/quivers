def _poly_frame() -> pd.DataFrame:
    """Build the frame of the R ``model.matrix`` oracle.

    Returns
    -------
    pandas.DataFrame
        An ordered factor of five levels, a covariate and a factor.
    """
    levels = ["lo", "mid", "hi", "top", "max"]
    order = [1, 2, 3, 4, 5, 2, 3, 1, 5, 4]
    frame = pd.DataFrame(
        {
            "o": pd.Categorical(
                [levels[i - 1] for i in order], categories=levels, ordered=True
            ),
            "z": [0.5, -1, 2, 0.25, 1.5, -0.5, 3, 1, -2, 0.75],
            "f": ["a", "b"] * 5,
        }
    )
    frame["y"] = frame.z + 1 + np.arange(10) * 0.1
    return frame


