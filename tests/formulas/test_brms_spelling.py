def test_registry_lists_each_family_once_and_rejects_unknown_names() -> None:
    """Aliases are not listed, and a name brms rejects stays unknown."""
    assert "negbinomial" in families and "negbinomial" not in list(families)
    assert len(set(families)) == len(families)
    for unknown in ("neg_binomial", "inverse_gauss", "nope", ""):
        assert unknown not in families
        assert canonical_family_name(unknown, families) == unknown
    with pytest.raises(ValueError, match="unknown family 'nope'"):
        fit("y ~ x", data=_frame(), family="nope", **SVI)


def test_alias_fit_is_the_registered_family() -> None:
    """A fit under a brms family name is the fit under the registered name."""
    frame = _frame()
    alias = fit("count ~ x", data=frame, family="negbinomial", seed=3, **SVI)
    named = fit("count ~ x", data=frame, family="negative_binomial", seed=3, **SVI)
    assert alias.family.name == "negative_binomial"
    assert alias.qvr_source == named.qvr_source
    assert alias.update(num_steps=2).family.name == "negative_binomial"


def test_brmsfamily_links_thresholds_and_refusals() -> None:
    """``brmsfamily`` sets links and thresholds and refuses what does not apply."""
    assert brmsfamily("bernoulli", "identity").location_link.name == "identity"
    assert brmsfamily("gaussian") is families["gaussian"]
    student = brmsfamily("student", link_sigma="identity")
    assert {aux.name: aux.link.name for aux in student.aux_params}["sigma"] == (
        "identity"
    )
    ordinal = brmsfamily("cumulative", "probit", threshold="equidistant").ordinal
    assert ordinal is not None
    assert (ordinal.link, ordinal.thresholds) == ("probit", "equidistant")
    with pytest.raises(ValueError, match="unknown family"):
        brmsfamily("nope")
    with pytest.raises(ValueError, match="link_<parameter>"):
        brmsfamily("gaussian", sigma="log")
    with pytest.raises(ValueError, match="requires an ordinal family"):
        brmsfamily("gaussian", threshold="equidistant")


# -- bf, lf, nlf, set_nl ----------------------------------------------------------


def test_bf_takes_the_family_of_fit() -> None:
    """``fit(bf(y ~ x, zi ~ z), family=...)`` classifies ``zi`` under the family."""
    frame = _frame()
    model = fit(
        bf("count ~ x", "zi ~ z"), data=frame, family="zero_inflated_poisson", **SVI
    )
    stated = fit(
        bf("count ~ x", "zi ~ z", family="zero_inflated_poisson"), data=frame, **SVI
    )
    assert model.qvr_source == stated.qvr_source
    assert {"b_zi_Intercept", "b_zi_z"} <= set(model.variables())


def test_bf_without_a_family_is_gaussian_and_checked_at_fit() -> None:
    """Without any family the parameter formulas are checked as Gaussian."""
    frame = _frame()
    assert "b_sigma_z" in fit(bf("y ~ x", "sigma ~ z"), data=frame, **SVI).variables()
    with pytest.raises(ValueError, match="'zi' is not an auxiliary parameter"):
        fit(bf("count ~ x", "zi ~ z"), data=frame, **SVI)
    with pytest.raises(ValueError, match="'sigma' is not an auxiliary parameter"):
        fit(bf("count ~ x", "sigma ~ z"), data=frame, family="poisson", **SVI)
    with pytest.raises(ValueError, match="given both in bf"):
        fit(bf("y ~ x", family="student"), data=frame, family="skew_normal", **SVI)


def test_shared_parameter_formula_and_added_formulas() -> None:
    """``b1 + b2 ~ 1``, ``lf``, ``nlf``, ``set_nl`` and ``+ family`` build one model."""
    frame = _frame()
    shared = bf("y ~ b1 * exp(b2 * x)", "b1 + b2 ~ 1", nl=True)
    separate = bf("y ~ b1 * exp(b2 * x)", "b1 ~ 1", "b2 ~ 1", nl=True)
    assert shared.nonlinear == separate.nonlinear
    added = bf("y ~ b1 * exp(b2 * x)") + lf("b1 + b2 ~ 1") + set_nl()
    assert added.nonlinear == separate.nonlinear
    scale = bf("y ~ x") + lf("sigma ~ 0 + z") + families["skew_normal"]
    model = fit(scale, data=frame, **SVI)
    assert model.family.name == "skew_normal" and "b_sigma_z" in model.variables()
    derived = bf("y ~ a + c", nl=True) + nlf("c ~ b * x^2") + lf("a + b ~ 1")
    assert set(fit(derived, data=frame, **SVI).variables()) == {
        "b_a_Intercept",
        "b_b_Intercept",
        "sigma",
    }
    with pytest.raises(ValueError, match="distinct parameter names"):
        bf("y ~ b1", "b1 + b1 ~ 1", nl=True)
    with pytest.raises(ValueError, match="has two formulas"):
        bf("y ~ b1", "b1 ~ 1", "b1 ~ x", nl=True)


def test_nlpar_prior_selects_the_nonlinear_intercept() -> None:
    """``prior(..., nlpar = "b1")`` reaches the intercept, brms's class b."""
    priors = (
        PriorSpec(distribution="Normal(1, 2)", nlpar="b1")
        + PriorSpec(distribution="Normal(0, 3)", nlpar="b2", coef="Intercept")
        + PriorSpec(distribution="Normal(0, 4)", nlpar="b2")
    )
    model = fit(
        bf("y ~ b1 * exp(b2 * x)", "b1 ~ 1", "b2 ~ 1 + z", nl=True),
        data=_frame(),
        priors=priors,
        **SVI,
    )
    table = {
        (row.nlpar, row.coef): row.prior
        for row in model.prior_summary().rows
        if row.nlpar is not None
    }
    assert table == {
        ("b1", "Intercept"): "Normal(loc=1, scale=2)",
        ("b2", "Intercept"): "Normal(loc=0, scale=3)",
        ("b2", "z"): "Normal(loc=0, scale=4)",
    }


# -- R and Stan expressions -------------------------------------------------------

_X = np.array([-1.7, -0.4, 0.3, 0.9, 2.2])
_U = np.array([0.05, 0.3, 0.5, 0.8, 0.97])
_P = np.array([0.4, 1.1, 2.0, 3.5, 6.0])

#: R expression, its value by an independent NumPy or SciPy form.
EXPRESSIONS: dict[str, np.ndarray] = {
    "x^2": _X**2,
    "-x^2": -(_X**2),
    "2^-x": 2.0**-_X,
    "p^u^2": _P ** (_U**2),
    "p ** 0.5 / 3": np.sqrt(_P) / 3,
    "1 - exp(-(p / 2)^1.5)": 1 - np.exp(-((_P / 2) ** 1.5)),
    "0.33 + 0.67 * inv_logit(x)": 0.33 + 0.67 * special.expit(_X),
    "logit(u)": special.logit(_U),
    "log_inv_logit(x)": np.log(special.expit(_X)),
    "log1m_inv_logit(x)": np.log1p(-special.expit(_X)),
    "inv_cloglog(x)": 1 - np.exp(-np.exp(_X)),
    "cloglog(u)": np.log(-np.log(1 - _U)),
    "Phi(x)": stats.norm.cdf(_X),
    "inv_Phi(u)": stats.norm.ppf(_U),
    "Phi_approx(x)": special.expit(0.07056 * _X**3 + 1.5976 * _X),
    "log1m(u)": np.log(1 - _U),
    "log1p_exp(x)": np.logaddexp(0, _X),
    "log1m_exp(-p)": np.log(-np.expm1(-_P)),
    "log_sum_exp(x, p)": np.logaddexp(_X, _P),
    "log_diff_exp(p, x)": np.log(np.exp(_P) - np.exp(_X)),
    "lbeta(p, u)": special.betaln(_P, _U),
    "cbrt(x)": np.cbrt(_X),
    "inv(p) + inv_sqrt(p) + inv_square(p)": 1 / _P + _P**-0.5 + _P**-2.0,
    "square(x) + fabs(x)": _X**2 + np.abs(_X),
    "fmin(x, u) - fmax(x, u)": np.minimum(_X, _U) - np.maximum(_X, _U),
    "fdim(x, u)": np.maximum(_X - _U, 0),
    "fmod(p, 0.7)": np.fmod(_P, 0.7),
    "hypot(x, p)": np.hypot(_X, _P),
    "exp2(x)": 2.0**_X,
    "step(x)": (_X >= 0).astype(float),
    "logm1(p + 1)": np.log(_P),
    "expp1(x)": np.exp(_X) + 1,
    "inv_logit_scaled(x, 1, 3)": 1 + 2 * special.expit(_X),
    "logit_scaled(p, 0, 7)": special.logit(_P / 7),
    "pi * x + log2() + log10() + sqrt2() + e() + pi()": math.pi * _X
    + math.log(2)
    + math.log(10)
    + math.sqrt(2)
    + math.e
    + math.pi,
    "lgamma(p) + digamma(p) + erf(x) + erfc(x)": special.gammaln(_P)
    + special.digamma(_P)
    + special.erf(_X)
    + special.erfc(_X),
    "exp(k) + pow(k, 2) + k / 2": np.exp(np.arange(1.0, 6.0))
    + np.arange(1.0, 6.0) ** 2
    + np.arange(1.0, 6.0) / 2,
}


@pytest.mark.parametrize("expression", sorted(EXPRESSIONS))
def test_r_expression_values(expression: str) -> None:
    """Each R or Stan expression evaluates to its independent closed form."""
    frame = pd.DataFrame({"x": _X, "u": _U, "p": _P, "k": np.arange(1, 6)})
    value = evaluate_r_expression(expression, frame, context="test")
    np.testing.assert_allclose(value, EXPRESSIONS[expression], rtol=1e-12, atol=1e-13)


def test_r_expression_precedence_and_literals() -> None:
    """Powers bind tighter than a sign, associate rightward, and literals are doubles."""
    read = lambda text: translate_r_expression(text, context="t").expression  # noqa: E731
    assert read("-x^2") == "(-pow(x, 2.0))"
    assert read("a^b^c") == "pow(a, pow(b, c))"
    assert read("2 * x") == "(2.0 * x)"
    assert read("x[0]") == "x[0]"
    integer = translate_r_expression(
        "exp(k) + real(k)", context="t", integer_names={"k"}
    )
    assert integer.expression == "(exp(real(k)) + real(k))"
    names = translate_r_expression(
        "r_g[a,Intercept] - x:z", context="t", name_pattern=HYPOTHESIS_NAME
    ).names
    assert names == ("r_g[a,Intercept]", "x:z")


