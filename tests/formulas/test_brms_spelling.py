def test_density_ratio_matches_brms() -> None:
    """The point-hypothesis evidence ratio equals brms's ``density_ratio``."""
    samples, prior = _draws()
    oracle = ORACLE["hypothesis"]
    a = samples["b_a"].reshape(-1).numpy()
    sigma = samples["sigma"].reshape(-1).numpy()
    np.testing.assert_allclose(r_density_at(a, 0.0), oracle["density"]["a"], rtol=1e-9)
    np.testing.assert_allclose(
        r_density_at(prior, 0.0), oracle["density"]["prior"], rtol=1e-9
    )
    # The sample lies above 0.6 and below 1.45: the extended-range branches.
    np.testing.assert_allclose(
        r_density_at(sigma, 0.6), oracle["density"]["below"], rtol=1e-9
    )
    np.testing.assert_allclose(
        r_density_at(sigma, 1.45), oracle["density"]["above"], rtol=1e-9
    )
    prior_draws = {
        "b_a": torch.tensor(prior).reshape(2, 200),
        "b_b": torch.zeros(2, 200, dtype=torch.float64),
    }
    table = hypothesis_table(samples, "a + b = 0", prefix="b_", prior=prior_draws)
    np.testing.assert_allclose(
        table.rows[0].evid_ratio, oracle["density_ratio"], rtol=1e-9
    )
    ratio = table.rows[0].evid_ratio
    np.testing.assert_allclose(table.rows[0].post_prob, ratio / (1 + ratio), rtol=1e-14)
    assert table.prior_samples is not None


def test_hypothesis_parsing_and_detection() -> None:
    """Strings split as in brms; contrast expressions are not hypothesis strings."""
    assert parse_hypothesis(" a + b = 0 ").contrast == "(a+b)"
    assert parse_hypothesis("a>b").contrast == "(a)-(b)"
    assert parse_hypothesis("a < 0.2").sign == "<"
    for bad in ("a >= 0", "a == b", "a", "a > b > c"):
        with pytest.raises(ValueError, match="left \\(= OR < OR >\\) right"):
            parse_hypothesis(bad)
    assert is_brms_hypothesis("x > 0") and is_brms_hypothesis(["x > 0"])
    assert not is_brms_hypothesis("x - z")
    assert not is_brms_hypothesis("select(x > 0.0, x, z)")
    with pytest.raises(ValueError, match=r"alpha' must be a single value in \[0,1\]"):
        hypothesis_table(_draws()[0], "b_a > 0", alpha=1.5)


def test_one_sided_evidence_counts_and_infinite_ratio() -> None:
    """The one-sided ratio is a count ratio, with probability one when all agree."""
    draws = {"v": torch.tensor([[0.5, 1.0, -0.25, 2.0]], dtype=torch.float64)}
    row = hypothesis_table(draws, "v > 0").rows[0]
    assert row.evid_ratio == 3.0 and row.post_prob == 0.75 and row.star == ""
    certain = hypothesis_table(draws, "v > -1").rows[0]
    assert math.isinf(certain.evid_ratio) and certain.post_prob == 1.0
    assert certain.star == "*"
    assert certain.hypothesis == "(v)-(-1) > 0"


def test_fit_hypothesis_classes_groups_and_scopes() -> None:
    """``class``, ``group`` and ``scope`` select parameters as brms does."""
    rng = np.random.default_rng(0)
    frame = _frame(40).assign(w=rng.normal(size=40))
    model = fit(
        "y ~ x * z + (1 + x | g)", data=frame, sample_prior="yes", seed=1, **SVI
    )
    named = model.variables()
    table = _table(model.hypothesis(["x > 0", "x + z = 0", "x:z < 0"]))
    assert list(table.to_frame().columns) == [
        "Hypothesis",
        "Estimate",
        "Est.Error",
        "CI.Lower",
        "CI.Upper",
        "Evid.Ratio",
        "Post.Prob",
        "Star",
    ]
    assert table.rows[0].estimate == pytest.approx(
        float(named["b_x"].double().mean()), rel=1e-12
    )
    # A point hypothesis with retained prior draws has an evidence ratio.
    assert math.isfinite(table.rows[1].evid_ratio)
    scale = _table(model.hypothesis("Intercept - x > 0", class_="sd", group="g"))
    difference = named["sd_g__Intercept"].double() - named["sd_g__x"].double()
    assert scale.rows[0].estimate == pytest.approx(float(difference.mean()), rel=1e-12)
    signal = _table(
        model.hypothesis(
            "sd_g__Intercept^2 / (sd_g__Intercept^2 + sigma^2) = 0", class_=None
        )
    )
    variance = named["sd_g__Intercept"].double() ** 2
    ratio = variance / (variance + named["sigma"].double() ** 2)
    assert signal.rows[0].estimate == pytest.approx(float(ratio.mean()), rel=1e-12)
    levels = _table(
        model.hypothesis(["Intercept + x > 0", "x < 0"], scope="coef", group="g")
    )
    assert [row.group for row in levels.rows] == list("abcd") * 2
    assert "Group" in levels.to_frame().columns
    with pytest.raises(ValueError, match=r"cannot be found in the model: \['b_w'\]"):
        model.hypothesis("w > 0")
    with pytest.raises(ValueError, match="'group' should be one of"):
        model.hypothesis("x > 0", scope="ranef", group="nope")
    # A contrast expression keeps its own result type.
    assert not isinstance(model.hypothesis("x - z"), HypothesisTable)
    assert "Hypothesis Tests for class b:" in str(table)


