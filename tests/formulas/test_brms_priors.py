def test_improper_flat_scores_zero_and_refuses_draws():
    frame = FRAME
    formula = formula_from_data("y ~ x", frame)
    lens = FormulaToQVRModule(families["gaussian"], default_priors="brms")
    module, _ = lens.forward(formula)
    assert improper_sites(module) == ("beta_x",)
    previous = torch.get_default_dtype()
    torch.set_default_dtype(torch.double)
    try:
        program = Compiler(module, families=FLAT_CATALOG).compile().morphism
        observations = {
            name: value.double()
            for name, value in lens.fixed_column_observations(formula).items()
        } | {"y": torch.tensor(frame.y.to_numpy(), dtype=torch.double)}
        intercept = torch.tensor(0.4, requires_grad=True)
        slope = torch.tensor(-0.7, requires_grad=True)
        sigma = torch.tensor(1.3, requires_grad=True)
        sites = {"intercept_centered": intercept, "beta_x": slope, "sigma": sigma}
        recorded = trace(program, torch.zeros(1, 1), observations | sites)
        x = observations["x"]
        mean = intercept - float(np.mean(frame.x)) * slope + slope * x
        density = (
            torch.distributions.StudentT(3.0, 0.3, 2.5).log_prob(intercept)
            + torch.distributions.StudentT(3.0, 0.0, 2.5).log_prob(sigma)
            + math.log(2.0)
            + torch.distributions.Normal(mean, sigma).log_prob(observations["y"]).sum()
        )
        torch.testing.assert_close(
            recorded.log_joint.sum(), density, atol=1e-12, rtol=1e-12
        )
        actual = torch.autograd.grad(
            recorded.log_joint.sum(), (intercept, slope, sigma), create_graph=True
        )
        expected = torch.autograd.grad(
            density, (intercept, slope, sigma), create_graph=True
        )
        for a, e in zip(actual, expected, strict=True):
            torch.testing.assert_close(a, e, atol=1e-11, rtol=1e-11)
        # Second derivatives in the flat coordinate come from the likelihood alone.
        hessian = torch.autograd.grad(actual[1], slope)[0]
        torch.testing.assert_close(
            hessian, torch.autograd.grad(expected[1], slope)[0], atol=1e-10, rtol=1e-10
        )
    finally:
        torch.set_default_dtype(previous)
    fitted = fit(
        "y ~ x",
        data=frame,
        default_priors="brms",
        num_warmup=30,
        num_samples=10,
        num_chains=1,
        seed=3,
    )
    with pytest.raises(ValueError, match="'beta_x' carry the improper flat prior"):
        fitted.prior_draws(num_samples=2)
    with pytest.raises(ValueError, match="'beta_x' carry the improper flat prior"):
        fit(
            "y ~ x",
            data=frame,
            default_priors="brms",
            sample_prior="only",
            num_warmup=2,
            num_samples=2,
            num_chains=1,
        )
    sampler = SMC(MetropolisKernel(RandomWalkProposal(0.5)), num_particles=8, seed=0)
    with pytest.raises(ValueError, match="SMC evidence requires a proper prior"):
        fitted.evidence(sampler)


def test_flat_prior_bounds_choose_the_law():
    table = validate_prior(
        PriorSpec(distribution=ImproperFlat(), class_="b", lower=0.0)
        + PriorSpec(distribution=ImproperFlat(), class_="sigma", upper=4.0),
        "y ~ x",
        data=FRAME,
    )
    assert table.row("beta_x").prior == "flat on (0, inf)"
    assert table.row("sigma").prior.startswith("Uniform(")
    with pytest.raises(ValueError, match="supports no bound"):
        validate_prior(
            PriorSpec(distribution=ImproperFlat(), class_="b", upper=1.0),
            "y ~ x",
            data=FRAME,
        )


def test_constant_priors_fix_coefficients_and_scales():
    rules = PriorSpec(distribution=ConstantPrior(value=1.5), class_="b", coef="x")
    rules = rules + PriorSpec(
        distribution=ConstantPrior(value=0.4), class_="sd", group="g"
    )
    table = validate_prior(rules, "y ~ x + z + (1 | g)", data=FRAME)
    assert table.row("beta_x").prior == "constant(1.5)"
    assert table.row("sigma_g_Intercept").prior == "constant(0.4)"
    fitted = fit(
        "y ~ x + z + (1 | g)",
        data=FRAME,
        priors=rules,
        num_warmup=40,
        num_samples=10,
        num_chains=1,
        seed=5,
    )
    draws = fitted.draws()
    assert torch.all(draws["beta_x"] == 1.5)
    assert torch.all(draws["sigma_g_Intercept"] == 0.4)
    assert "beta_x" not in fitted.posterior.samples
    effects = fitted.fixed_effects()
    assert torch.all(effects["x"] == 1.5)
    with pytest.raises(ValueError, match="takes one value"):
        validate_prior(
            PriorSpec(distribution=ConstantPrior(value=(1.0, 2.0)), class_="b"),
            "y ~ x",
            data=FRAME,
        )
    with pytest.raises((ValueError, dx.ValidationError), match="no bounds"):
        PriorSpec(distribution=ConstantPrior(value=1.0), lower=0.0)


def test_main_joins_shrinkage_classes_of_one_predictor():
    rules = PriorSpec(
        distribution=RegularizedHorseshoe(df=3.0, par_ratio=0.2, main=True),
        class_="b",
    ) + PriorSpec(distribution=RegularizedHorseshoe(), class_="sd")
    table = validate_prior(rules, "y ~ x + z + (1 | g)", data=FRAME)
    source = table.to_pandas()
    assert table.row("sigma_g_Intercept").prior.startswith("= prior_main_")
    assert source["prior"].str.contains("prior_main_").sum() >= 3
    two_mains = PriorSpec(distribution=R2D2(main=True), class_="b") + PriorSpec(
        distribution=R2D2(mean_R2=0.3, main=True), class_="sd"
    )
    with pytest.raises(ValueError, match="exactly one shrinkage rule"):
        validate_prior(two_mains, "y ~ x + (1 | g)", data=FRAME)
    mixed = PriorSpec(distribution=R2D2(main=True), class_="b") + PriorSpec(
        distribution=RegularizedHorseshoe(), class_="sd"
    )
    with pytest.raises(ValueError, match="cannot combine horseshoe and R2D2"):
        validate_prior(mixed, "y ~ x + (1 | g)", data=FRAME)
    with pytest.raises(ValueError, match="takes no bounds"):
        validate_prior(
            PriorSpec(distribution=R2D2(), class_="sd", lower=0.1),
            "y ~ x + (1 | g)",
            data=FRAME,
        )


def test_prior_summary_reports_fitted_priors():
    rules = PriorSpec(distribution="Normal(0, 1)", class_="b", tag="weak")
    fitted = fit(
        "y ~ x",
        data=FRAME,
        priors=rules,
        default_priors="brms",
        method="svi",
        num_steps=5,
        seed=1,
    )
    summary = fitted.prior_summary()
    assert summary.policy == "brms"
    assert summary.row("beta_x").source == "user"
    assert summary.row("beta_x").tag == "weak"
    assert summary.row("intercept_centered").source == "default"
    assert (
        summary.rows
        == validate_prior(rules, "y ~ x", data=FRAME, default_priors="brms").rows
    )
    assert isinstance(fitted.draws(num_samples=3)["intercept"], torch.Tensor)
