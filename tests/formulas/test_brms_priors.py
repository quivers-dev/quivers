# brms 2.23.0 family-specific defaults that differ from the 2.20.4 oracle:
# R/family-lists.R (.family_negbinomial), prior = inv_gamma(0.4, 0.3) for an
# estimated shape with the identity link (brms NEWS, #1614).
PINNED_OVERRIDES = {("negbinomial", "shape"): ("inv_gamma", (0.4, 0.3))}

# brms class name -> quivers class name, where they differ.
CLASS_NAMES = {("negbinomial", "shape"): "disp"}


def _call(text: str) -> tuple[str, tuple]:
    """Parse ``name(a, b)`` or ``Name(k=v, ...)`` into a normalized tuple."""
    match = re.fullmatch(r"\s*(\w+)\((.*)\)\s*", text)
    assert match is not None, text
    name, body = match.groups()
    parts, depth, start = [], 0, 0
    for index, char in enumerate(body):
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(body[start:index])
            start = index + 1
    parts.append(body[start:])
    values = []
    for part in (p.strip() for p in parts if p.strip()):
        value = part.split("=", 1)[1] if re.match(r"^\w+=", part) else part
        values.append(_call(value) if "(" in value else float(value))
    return name, tuple(values)


def _expected(brms: dict) -> tuple[str, tuple]:
    """Translate a brms prior row into the quivers constructor it implies."""
    name, args = _call(brms["prior"])
    lower = brms["lb"]
    if name == "student_t":
        if lower == "0" and args[1] == 0:
            return "HalfStudentT", (args[0], args[2])
        return "StudentT", args
    mapped = {
        "gamma": "Gamma",
        "beta": "Beta",
        "lkj": "LKJCholesky",
        "inv_gamma": "InverseGamma",
        "normal": "Normal",
        "logistic": "Logistic",
        "lognormal": "LogNormal",
    }[name]
    if lower not in ("", "0") and brms["class"] == "nu":
        return "Restrict", ((mapped, args), float(lower))
    return mapped, args


def _rows(table, *, klass, dpar, coef=None):
    return [
        row
        for row in table.rows
        if row.class_ == klass
        # An estimated auxiliary parameter is its own quivers dpar.
        and (row.dpar or "mu") in {dpar or "mu", klass}
        and (coef is None or row.coef == coef)
    ]


# Cases of ARMA, mo(), me() and mi() terms are checked, per response, in
# test_brms_flat_defaults.py.
@pytest.mark.parametrize(
    "case", [c["name"] for c in ORACLE["cases"] if c["name"] in CASES]
)
def test_brms_policy_reproduces_default_prior(case):
    record = next(c for c in ORACLE["cases"] if c["name"] == case)
    formula, family, options = CASES[case]
    table = default_prior(
        formula, data=FRAME, family=family, default_priors="brms", **options
    )
    assert table.policy == "brms"
    assert all(row.source == "default" for row in table.rows)
    for brms in record["table"]:
        klass = CLASS_NAMES.get((case, brms["class"]), brms["class"])
        dpar = brms["dpar"] or "mu"
        if case == "cumulative" and klass == "Intercept":
            # Thresholds keep quivers's identified coordinates (documented).
            continue
        if klass == "b":
            if brms["coef"] and case != "smooth":
                # brms and quivers name the same population coefficients.
                assert _rows(table, klass="b", dpar=dpar, coef=brms["coef"]), brms
            for row in _rows(table, klass="b", dpar=dpar):
                assert row.prior == "flat", (case, row)
            continue
        if not brms["prior"]:
            if brms["coef"] and klass == "sd":
                assert _rows(table, klass="sd", dpar=dpar, coef=brms["coef"]), brms
            continue
        expected = _expected(brms)
        if (case, brms["class"]) in PINNED_OVERRIDES:
            name, args = PINNED_OVERRIDES[(case, brms["class"])]
            expected = _expected(
                {**brms, "prior": f"{name}({', '.join(map(str, args))})"}
            )
        rows = _rows(table, klass=klass, dpar=dpar)
        assert rows, (case, brms)
        for row in rows:
            name, args = _call(row.prior)
            assert name == expected[0], (case, row, expected)
            flat_actual = np.array(_flatten(args))
            flat_expected = np.array(_flatten(expected[1]))
            np.testing.assert_allclose(flat_actual, flat_expected, rtol=0, atol=1e-12)


def _flatten(args):
    out = []
    for value in args:
        if isinstance(value, tuple) and value and isinstance(value[0], str):
            out.extend(_flatten(value[1]))
        elif isinstance(value, tuple):
            out.extend(_flatten(value))
        else:
            out.append(value)
    return out


def test_default_scale_arguments_follow_brms_rounding_and_links():
    pos = FRAME["pos"].to_numpy()
    rounding = ORACLE["rounding"]
    location, scale = scale_prior_arguments(pos, "log", center=False)
    assert location == rounding["median_log"]
    assert scale == max(2.5, rounding["mad_log"])
    y = FRAME["y"].to_numpy()
    assert r_mad(y) == pytest.approx(1.4826 * np.median(np.abs(y - np.median(y))))
    # A negative response under the log link has no finite mad: brms keeps 2.5.
    assert scale_prior_arguments(y, "log", center=True) == (0.0, 2.5)
    # Factor and vector responses, and links brms does not apply, keep 0, 2.5.
    assert scale_prior_arguments(None, "identity", center=False) == (0.0, 2.5)
    assert scale_prior_arguments(pos, "logit", center=False) == (0.0, 2.5)


def test_validate_prior_marks_user_rows_tags_and_bounds():
    rules = (
        PriorSpec(distribution="Normal(0, 2)", class_="b", lower=0.0, tag="slopes")
        + PriorSpec(distribution="Normal(1, 0.5)", class_="b", coef="x")
        + PriorSpec(distribution="StudentT(3, 0, 1)", class_="sigma", tag="noise")
    )
    table = validate_prior(rules, "y ~ x + z", data=FRAME, default_priors="brms")
    frame = table.to_pandas()
    assert list(frame.columns[:11]) == [
        "prior",
        "class",
        "coef",
        "group",
        "resp",
        "dpar",
        "nlpar",
        "lb",
        "ub",
        "tag",
        "source",
    ]
    by_coef = {row.coef: row for row in table.rows if row.class_ == "b"}
    assert by_coef["x"].source == "user" and by_coef["x"].prior.startswith("Normal")
    assert by_coef["z"].source == "user" and by_coef["z"].tag == "slopes"
    assert by_coef["z"].lower == 0.0
    sigma = table.row("sigma")
    assert sigma.source == "user" and sigma.tag == "noise" and sigma.lower == 0.0
    intercept = table.row("intercept_centered")
    assert intercept.source == "default"
    # The oracle's validated table: the same intercept default under user b priors.
    brms_intercept = next(r for r in ORACLE["validated"] if r["class"] == "Intercept")
    assert _call(intercept.prior)[1] == _call(brms_intercept["prior"])[1]


