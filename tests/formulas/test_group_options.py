"""brms ``gr(by = )``, ``gr(dist = "student")``, and ``gr(pw = )``.

The oracle ``oracles/brms_group_options.json`` is generated by
``oracles/brms_group_options.R`` from brms 2.20.4's ``make_standata``,
``make_stancode``, and ``get_prior``. ``pw`` postdates that release, so its
density is pinned from the brms 2.23 source (``R/stan-predictor.R``):
``target += PW[j] * std_normal_lpdf(z[, j])``.
"""

import json
import math
import pathlib
from typing import Literal

import numpy as np
import pandas as pd
import pytest
import torch

from quivers.continuous.programs import MonadicProgram
from quivers.dsl import Compiler
from quivers.formulas import FormulaToQVRModule, families, fit, formula_from_data
from quivers.formulas._fit import BayesianFit
from quivers.inference.trace import trace
from quivers.modeling import load_fit, save_fit

ORACLE = json.loads(
    (pathlib.Path(__file__).parent / "oracles" / "brms_group_options.json").read_text()
)


def _case(formula: str) -> dict:
    return next(case for case in ORACLE["cases"] if case["formula"] == formula)


def _program(module) -> MonadicProgram:
    program = Compiler(module).compile().morphism
    assert isinstance(program, MonadicProgram)
    return program


def _lens(text: str, frame: pd.DataFrame):
    formula = formula_from_data(text, frame)
    lens = FormulaToQVRModule(families["gaussian"])
    module, _ = lens.forward(formula)
    values = dict(lens.fixed_column_observations(formula))
    values["y"] = torch.as_tensor(formula.response_values.copy())
    values["g_idx"] = torch.tensor(formula.group_indices["g"], dtype=torch.long)
    return formula, lens, _program(module), values


def _cholesky(generator: np.random.Generator, size: int) -> np.ndarray:
    raw = generator.normal(size=(size, size))
    covariance = raw @ raw.T + size * np.eye(size)
    scale = np.sqrt(np.diag(covariance))
    return np.linalg.cholesky(covariance / np.outer(scale, scale))


@pytest.mark.parametrize("formula", [case["formula"] for case in ORACLE["cases"]])
def test_codes_and_prior_catalogue_match_brms(formula):
    case = _case(formula)
    parsed = formula_from_data(formula, pd.DataFrame(ORACLE["data"]))
    np.testing.assert_array_equal(
        np.asarray(parsed.group_indices["g"]) + 1, case["data"]["J_1"]
    )
    option = parsed.grouping.option(parsed.random_terms[0].options)
    assert option is not None
    lens = FormulaToQVRModule(families["gaussian"])
    lens.forward(parsed)
    targets = {target.site: target for target in lens.prior_targets}
    if "Nby_1" in case["data"]:
        np.testing.assert_array_equal(
            np.asarray(option.by_codes) + 1, case["data"]["Jby_1"]
        )
        assert len(option.by_levels) == case["data"]["Nby_1"]
        for slope in ("Intercept", "x"):
            # brms: matrix<lower=0>[M_1, Nby_1] sd_1.
            assert targets[f"sigma_g_{slope}"].shape == (case["data"]["Nby_1"],)
        cors = sorted(site for site in targets if site.startswith("cor_"))
        # brms: cholesky_factor_corr[M_1] L_1[Nby_1], one LKJ per by level.
        expected = case["data"]["Nby_1"] if "||" not in formula else 0
        assert len(cors) == expected
        assert all(targets[site].coef in option.by_levels for site in cors)
    else:
        [df] = [row for row in case["prior"] if row["class"] == "df"]
        assert (df["prior"], df["lb"], df["group"]) == ("gamma(2, 0.1)", "1", "g")
        assert targets["df_g"].class_ == "df" and targets["df_g"].lower == 1.0
        assert targets["df_g"].group == "g"


def _brms_effects(case: dict, parameters: dict, levels: int) -> np.ndarray:
    """brms's group-level effects from its generated Stan statements."""
    z, sd = parameters["z"], parameters["sd"]
    if "Nby_1" in case["data"]:
        jby = np.asarray(case["data"]["Jby_1"], dtype=int) - 1
        if "||" in case["formula"]:
            # r_1_k = transpose(sd_1[k, Jby_1]) .* z_1[k]
            return np.stack([sd[k, jby] * z[k] for k in range(len(z))], axis=1)
        # scale_r_cor_by: r[j] = (diag_pre_multiply(SD[, Jby[j]], L[Jby[j]]) * z[, j])'
        return np.stack(
            [
                np.diag(sd[:, jby[j]]) @ parameters["L"][jby[j]] @ z[:, j]
                for j in range(levels)
            ]
        )
    dfm = np.sqrt(parameters["df"] * parameters["udf"])
    if len(z) == 1:
        return (dfm * (sd[0] * z[0]))[:, None]
    # r_1 = rep_matrix(dfm_1, M_1) .* scale_r_cor(z_1, sd_1, L_1)
    return dfm[:, None] * (np.diag(sd) @ parameters["L"] @ z).T


@pytest.mark.parametrize("formula", [case["formula"] for case in ORACLE["cases"]])
def test_group_effects_equal_brms_generated_stan_statements(formula):
    case = _case(formula)
    frame = pd.DataFrame(ORACLE["data"])
    parsed, _, program, values = _lens(formula, frame)
    slopes = [term.slope for term in parsed.random_terms]
    levels = len(parsed.group_levels["g"])
    generator = np.random.default_rng(12)
    z = generator.normal(size=(len(slopes), levels))
    parameters: dict = {"z": z}
    option = parsed.grouping.option(parsed.random_terms[0].options)
    assert option is not None
    if "Nby_1" in case["data"]:
        nby = case["data"]["Nby_1"]
        parameters["sd"] = generator.uniform(0.5, 1.5, size=(len(slopes), nby))
        parameters["L"] = [_cholesky(generator, len(slopes)) for _ in range(nby)]
        for b, factor in enumerate(parameters["L"]):
            if len(slopes) > 1 and "||" not in formula:
                values[f"cor_g_by{b + 1}"] = torch.as_tensor(factor)
    else:
        parameters["sd"] = generator.uniform(0.5, 1.5, size=len(slopes))
        parameters["df"] = 4.5
        parameters["udf"] = generator.uniform(0.1, 0.9, size=levels)
        values["df_g"] = torch.tensor(parameters["df"], dtype=torch.float64)
        values["udf_g"] = torch.as_tensor(parameters["udf"])
        if len(slopes) > 1:
            parameters["L"] = _cholesky(generator, len(slopes))
            values["cor_g"] = torch.as_tensor(parameters["L"])
    for k, slope in enumerate(slopes):
        name = "Intercept" if slope == "Intercept" else slope
        values[f"sigma_g_{name}"] = torch.as_tensor(parameters["sd"][k])
        values[f"z_g_{name}"] = torch.as_tensor(z[k])
    values["intercept"] = torch.tensor(0.0, dtype=torch.float64)
    values["beta_x"] = torch.tensor(0.0, dtype=torch.float64)
    values["sigma"] = torch.tensor(1.0, dtype=torch.float64)
    sites = trace(program, torch.zeros(1, 1), values).sites
    expected = _brms_effects(case, parameters, levels)
    for k, slope in enumerate(slopes):
        latent = "alpha_g" if slope == "Intercept" else f"beta_g_{slope}"
        np.testing.assert_allclose(
            sites[latent].value.reshape(-1).detach().numpy(),
            expected[:, k],
            rtol=1e-12,
            atol=1e-12,
        )


def test_student_density_and_derivatives_match_hand_written_oracle():
    frame = pd.DataFrame(ORACLE["data"])
    _, _, program, observed = _lens("y ~ x + (1 | gr(g, dist = 'student'))", frame)
    g = torch.tensor([ord(v) - ord("a") for v in frame["g"]])
    x = torch.tensor(frame["x"].to_numpy(dtype=float))
    y = observed["y"]
    beta_scale = 5.0 / float(np.sqrt(np.mean(frame["x"].to_numpy() ** 2)))

    def split(point):
        return (
            point[0],
            point[1],
            point[2],
            point[3:7],
            point[7],
            point[8:12],
            point[12],
        )

    def actual(point):
        intercept, beta, df, udf, sd, z, sigma = split(point)
        values = {
            **observed,
            "intercept": intercept,
            "beta_x": beta,
            "df_g": df,
            "udf_g": udf,
            "sigma_g_Intercept": sd,
            "z_g_Intercept": z,
            "sigma": sigma,
        }
        joint = trace(program, point.new_zeros(1, 1), values).log_joint
        assert joint is not None
        return joint.sum()

    def oracle(point):
        intercept, beta, df, udf, sd, z, sigma = split(point)
        gamma = torch.distributions.Gamma(point.new_tensor(2.0), point.new_tensor(0.1))
        # df ~ gamma(2, 0.1) restricted to df > 1, normalized on that interval.
        truncation = torch.log1p(
            -torch.special.gammainc(point.new_tensor(2.0), point.new_tensor(0.1 * 1.0))
        )
        effects = torch.sqrt(df * udf) * sd * z
        mu = intercept + beta * x + effects[g]
        normal = torch.distributions.Normal
        return (
            normal(0.0, 5.0).log_prob(intercept)
            + normal(0.0, beta_scale).log_prob(beta)
            + gamma.log_prob(df)
            - truncation
            # inv_chi_square(df) is InverseGamma(df / 2, 1 / 2).
            + torch.distributions.InverseGamma(df / 2, point.new_tensor(0.5))
            .log_prob(udf)
            .sum()
            + torch.distributions.HalfNormal(1.0).log_prob(sd)
            + normal(0.0, 1.0).log_prob(z).sum()
            + torch.distributions.HalfCauchy(2.0).log_prob(sigma)
            + normal(mu, sigma).log_prob(y).sum()
        )

    point = torch.tensor(
        [0.1, -0.2, 3.5, 0.4, 0.7, 1.1, 0.5, 0.9, 0.3, -0.6, 1.2, -0.1, 1.4],
        dtype=torch.float64,
        requires_grad=True,
    )
    torch.testing.assert_close(actual(point), oracle(point))
    torch.testing.assert_close(
        torch.autograd.functional.jacobian(actual, point),
        torch.autograd.functional.jacobian(oracle, point),
    )
    torch.testing.assert_close(
        torch.autograd.functional.hessian(actual, point),
        torch.autograd.functional.hessian(oracle, point),
    )


def test_prior_weights_scale_each_level_standard_normal_density():
    frame = pd.DataFrame(ORACLE["data"])
    weights = {"a": 2.0, "b": 0.5, "c": 1.0, "d": 0.0}
    frame["w"] = [weights[label] for label in frame["g"]]
    _, _, weighted, values = _lens("y ~ x + (1 + x | gr(g, pw = w))", frame)
    _, _, plain, _ = _lens("y ~ x + (1 + x | g)", frame)
    generator = np.random.default_rng(3)
    for name in ("z_g_Intercept", "z_g_x"):
        values[name] = torch.as_tensor(generator.normal(size=4))
    values.update(
        {
            "cor_g": torch.as_tensor(_cholesky(generator, 2)),
            "sigma_g_Intercept": torch.tensor(0.8, dtype=torch.float64),
            "sigma_g_x": torch.tensor(1.3, dtype=torch.float64),
            "intercept": torch.tensor(0.2, dtype=torch.float64),
            "beta_x": torch.tensor(-0.3, dtype=torch.float64),
            "sigma": torch.tensor(1.1, dtype=torch.float64),
        }
    )
    with_weights = trace(weighted, torch.zeros(1, 1), values).log_joint
    without = trace(plain, torch.zeros(1, 1), values).log_joint
    assert with_weights is not None and without is not None
    difference = (with_weights - without).sum()
    # brms: target += PW[j] * std_normal_lpdf(z[, j]); the plain model has PW = 1.
    pw = torch.tensor([weights[label] for label in "abcd"], dtype=torch.float64)
    log_density = sum(
        -0.5 * values[name] ** 2 - 0.5 * math.log(2 * math.pi)
        for name in ("z_g_Intercept", "z_g_x")
    )
    torch.testing.assert_close(difference, ((pw - 1) * log_density).sum())


def test_invalid_options_are_refused():
    frame = pd.DataFrame(ORACLE["data"])
    with pytest.raises(ValueError, match="correspond to multiple levels"):
        formula_from_data("y ~ (1 | gr(g, by = x))", frame)
    for by in ("f", "cbind(f)", "cbind(f, f, f)", "c(f, f)"):
        with pytest.raises(ValueError, match="cbind|as many columns"):
            formula_from_data(f"y ~ (1 | mm(g, f, by = {by}))", frame)
    with pytest.raises(ValueError, match="unknown arguments"):
        formula_from_data("y ~ (1 | mm(g, f, pw = n))", frame)
    with pytest.raises(ValueError, match="finite and nonnegative"):
        formula_from_data("y ~ (1 | gr(g, pw = n))", frame.assign(n=-1.0))
    fitted = fit("y ~ (1 | gr(g, by = f))", data=frame, method="svi", num_steps=1)
    unseen = frame.iloc[:2].assign(g=["new", "a"], f=["r", "p"])
    with pytest.raises(ValueError, match="needs one fitted level"):
        fitted.posterior_epred(new_data=unseen, num_samples=1, allow_new_levels=True)


def _frame(rows: int = 48) -> pd.DataFrame:
    generator = np.random.default_rng(21)
    index = np.arange(rows)
    frame = pd.DataFrame(
        {
            "x": generator.normal(size=rows),
            "g": np.array(list("abcdef"))[index % 6],
        }
    )
    frame["f"] = np.where(frame["g"].isin(list("abc")), "p", "q")
    frame["w"] = np.where(frame["g"].isin(list("ab")), 2.0, 1.0)
    frame["y"] = 0.3 * frame["x"] + generator.standard_t(3, size=rows) * 0.4
    return frame


FORMULAS = (
    "y ~ x + (1 + x | gr(g, by = f, dist = 'student', pw = w))",
    "y ~ x + (1 + x || gr(g, by = f))",
)


def _fit_with(
    method: Literal["svi", "hmc", "nuts"], formula: str, frame: pd.DataFrame
) -> BayesianFit:
    if method == "svi":
        return fit(formula, data=frame, method="svi", num_steps=3, seed=2)
    return fit(
        formula,
        data=frame,
        method=method,
        num_warmup=2,
        num_samples=2,
        num_chains=1,
        seed=2,
    )


@pytest.mark.parametrize("formula", FORMULAS)
@pytest.mark.parametrize("method", ["svi", "hmc", "nuts"])
def test_every_inference_method_predicts_new_levels(
    method: Literal["svi", "hmc", "nuts"], formula: str
):
    fitted = _fit_with(method, formula, _frame())
    fresh = (
        _frame().iloc[:4].assign(g=["a", "new", "f", "other"], f=["p", "q", "q", "p"])
    )
    for policy in ("uncertainty", "gaussian", "old_levels"):
        draws = fitted.posterior_predict(
            new_data=fresh,
            num_samples=2,
            seed=1,
            allow_new_levels=True,
            sample_new_levels=policy,
        )
        assert draws.shape[-1] == 4 and torch.isfinite(draws).all()
    likelihood = fitted.log_likelihood(new_data=fresh.iloc[[0, 2]], num_samples=2)
    values = (
        likelihood
        if isinstance(likelihood, torch.Tensor)
        else next(iter(likelihood.values()))
    )
    assert torch.isfinite(values).all()


def test_training_rows_update_and_artifact_round_trip(tmp_path):
    frame = _frame()
    fitted = fit(FORMULAS[0], data=frame, method="svi", num_steps=2, seed=3)
    torch.testing.assert_close(
        fitted.posterior_linpred(new_data=frame, num_samples=3, seed=4),
        fitted.posterior_linpred(num_samples=3, seed=4),
    )
    refit = fitted.update(data=frame.iloc[:36].reset_index(drop=True))
    assert refit.formula.grouping.option(refit.formula.random_terms[0].options)
    fresh = frame.iloc[:3]
    expected = fitted.posterior_epred(new_data=fresh, num_samples=2, seed=9)
    path = tmp_path / "options.qfit"
    save_fit(fitted, path)
    restored = load_fit(path)
    assert isinstance(restored, BayesianFit)
    assert restored.formula.grouping == fitted.formula.grouping
    torch.testing.assert_close(
        restored.posterior_epred(new_data=fresh, num_samples=2, seed=9), expected
    )
