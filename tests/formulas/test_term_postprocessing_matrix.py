def _chain_matrix(rows: int) -> np.ndarray:
    """Return the adjacency matrix of a path graph over ``rows`` rows."""
    matrix = np.zeros((rows, rows))
    for i in range(rows - 1):
        matrix[i, i + 1] = matrix[i + 1, i] = 1.0
    return matrix


