def _frame() -> pd.DataFrame:
    """Build the shared 24-row frame with every column the cases read."""
    r = np.arange(N)
    rng = np.random.default_rng(0)
    d = pd.DataFrame(
        {
            "x": np.sin(r * 0.7),
            "z": np.cos(r * 1.3),
            "w": 1.0 + (r % 3) * 0.5,
            "g": np.array(["a", "b", "c", "d"])[r % 4],
            "g2": np.array(["a", "b", "c", "d"])[(r + 1) % 4],
            "h": np.array(["p", "q"])[(r // 4) % 2],
            "f": np.array(["u", "v", "t"])[r % 3],
            "time": r % 6,
            "sub": r // 6,
            "se": 0.2 + 0.05 * (r % 4),
            "k": r % 4,
            "n": 10,
        }
    )
    d["by2"] = np.where(np.isin(d.g, ["a", "b"]), "L", "R")
    d["pwv"] = d.g.map({"a": 1.0, "b": 2.0, "c": 1.5, "d": 1.0})
    d["y"] = 1.0 + 0.5 * d.x - 0.3 * d.z + 0.3 * rng.standard_normal(N)
    d["y2"] = 0.5 - 0.2 * d.x + 0.3 * rng.standard_normal(N)
    d["ymis"] = d.y.where(r % 5 != 0)
    d["xmis"] = d.x.where(r % 7 != 0)
    d["pos"] = np.exp(0.3 * d.y)
    d["cnt"] = rng.poisson(3.0, N)
    d["succ"] = rng.binomial(10, 0.4, N)
    d["bin"] = (d.y > d.y.median()).astype(int)
    d["unit"] = 1 / (1 + np.exp(-d.y + 1))
    d["ordy"] = pd.Categorical(
        np.array(["lo", "mid", "hi", "top"])[(r * 7) % 4],
        categories=["lo", "mid", "hi", "top"],
        ordered=True,
    )
    d["caty"] = np.array(["A", "B", "C"])[(r * 5) % 3]
    d["keep"] = (r % 5) != 0
    d["cen"] = np.array([0, 1, -1, 0])[r % 4]
    d["c1"] = d.succ
    d["c2"] = 10 - d.succ
    d["c3"] = 3
    d["p1"] = d.unit * 0.5
    d["p2"] = (1 - d.unit) * 0.5
    d["p3"] = 0.5
    d["tot"] = d.c1 + d.c2 + d.c3
    d["known_bias"] = 0.1 * d.z
    return d


