#: Cases refitted by the k-fold cell, which costs two refits each.
KFOLD_CASES = frozenset(
    {"plain", "group", "s", "mixture", "cumulative", "joint_rescor", "brms_priors"}
)

#: Recorded-chain cases whose refit cell runs; the others repeat the same path.
NUTS_UPDATE_CASES = frozenset({"plain_nuts", "joint_nuts"})

MATRIX = [
    (model, cell)
    for model, case in MODELS.items()
    for cell in CELLS
    if (cell != "kfold" or model in KFOLD_CASES)
    and (cell != "update" or case.method == "svi" or model in NUTS_UPDATE_CASES)
]


@pytest.mark.parametrize(("model", "cell"), MATRIX, ids=lambda value: value)
def test_term_by_postprocessing_cell(
    model: str, cell: str, tmp_path: pathlib.Path
) -> None:
    ctx = Context(model)
    pattern = ctx.case.refuse.get(cell)
    arguments = (ctx, tmp_path) if cell == "artifact" else (ctx,)
    if pattern is None:
        CELLS[cell](*arguments)
        return
    # A located refusal is a ValueError, or the TypeError that the response
    # layer documents for a law without an analytic expectation.
    with pytest.raises((ValueError, TypeError), match=pattern):
        CELLS[cell](*arguments)


def test_every_case_declares_only_known_cells() -> None:
    for name, case in MODELS.items():
        assert set(case.refuse) <= set(CELLS), name
        assert case.oracle is None or case.oracle in ORACLE, name
