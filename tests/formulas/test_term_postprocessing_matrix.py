def _prediction(method: str, *, new: bool) -> Callable[[Context], None]:
    """Build the cell of one draw-level prediction method."""

    def cell(ctx: Context) -> None:
        options = _new(ctx) if new else {}
        if method == "posterior_epred":
            options = options | ctx.case.epred_options
        if new and ctx.case.new_refusal is not None:
            with pytest.raises(ValueError, match=ctx.case.new_refusal):
                getattr(ctx.fit, method)(**options, **ctx.draws)
            return
        value = getattr(ctx.fit, method)(**options, **ctx.draws)
        if method == "log_likelihood" and not new and ctx.case.missing_rows:
            missing = list(ctx.case.missing_rows)
            label = ctx.case.missing_response
            recorded = ctx.case.score_resp
            if recorded is None:
                scores = value[label]
            else:
                assert isinstance(ctx.fit, MultivariateFit)
                scores = ctx.fit.log_likelihood(resp=label, **ctx.draws)[label]
                if not ctx.fit.rescor:
                    other = ctx.fit.log_likelihood(resp=recorded, **ctx.draws)[recorded]
                    torch.testing.assert_close(
                        value["__".join(ctx.responses)], scores + other, rtol=0, atol=0
                    )
            assert bool((scores[..., missing] == 0).all())
            check_draws(ctx, scores, ctx.case.rows, what=f"{label} log_likelihood")
        check_draws(ctx, value, _rows(ctx, new=new), what=method)

    return cell


def on_new_rows(ctx: Context, call: Callable[[], object]) -> object | None:
    """Call a new-row prediction, or assert the case's documented refusal."""
    if ctx.case.new_refusal is None:
        return call()
    with pytest.raises(ValueError, match=ctx.case.new_refusal):
        call()
    return None


