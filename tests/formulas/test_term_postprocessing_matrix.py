def cell_update(ctx: Context) -> None:
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        again = ctx.fit.update(seed=1)
    assert type(again) is type(ctx.fit)
    assert list(again.variables(**ctx.draws)) == list(ctx.fit.variables(**ctx.draws))
    check_draws(
        ctx,
        again.posterior_linpred(**ctx.draws),
        _rows(ctx, new=False),
        what="update linpred",
    )


def cell_artifact(ctx: Context, tmp_path: pathlib.Path) -> None:
    path = tmp_path / "fit.qvrfit"
    save_fit(ctx.fit, path)
    restored = load_fit(path)
    assert type(restored) is type(ctx.fit)
    rows = {} if ctx.case.new_refusal is not None else _new(ctx)
    before = ctx.fit.posterior_linpred(**rows, **ctx.draws)
    after = restored.posterior_linpred(**rows, **ctx.draws)
    for a, b in zip(per_response(before), per_response(after), strict=True):
        torch.testing.assert_close(a, b)
    predicted = restored.posterior_predict(**rows, **ctx.draws)
    check_draws(
        ctx, predicted, _rows(ctx, new=bool(rows)), what="restored posterior_predict"
    )
    assert list(restored.variables(**ctx.draws)) == list(ctx.fit.variables(**ctx.draws))


def cell_diagnostics(ctx: Context) -> None:
    if ctx.case.method != "nuts":
        with pytest.raises(ValueError, match="recorded|MCMC|chains"):
            ctx.fit.rhat()
        return
    names = ctx.fit.variables()
    rhat = ctx.fit.rhat()
    ratio = ctx.fit.neff_ratio()
    assert set(rhat) == set(names) == set(ratio)
    assert all(np.isfinite(value) for value in ratio.values())
    assert len(ctx.fit.nuts_params()) > 0
    assert len(ctx.fit.log_posterior()) == ctx.total


def cell_group_coefficients(ctx: Context) -> None:
    """Per-level coefficients equal the program's own bindings at each draw.

    The oracle is the fitted program: each group block retains the name of
    its deterministic per-level coefficient binding, which a replay of the
    program at a draw evaluates from the sampled sites.
    """
    if ctx.case.joint or not ctx.case.groups:
        return
    fit_ = ctx.fit
    draws = fit_.draws(**ctx.draws)
    plan = fit_.prediction_plan
    bindings = {
        (member.prefix, layout.group, member.slope): member.coefficient
        for layout in plan.group_layouts
        for member in layout.members
    }
    checked = 0
    for _, prefix, predictor in fit_._predictor_items():
        if not predictor.random_terms:
            continue
        varying = fit_._random_effects(draws, ctx.shape, predictor, prefix)
        traces = list(replay(fit_, draws, ctx.shape))
        for term in predictor.random_terms:
            if (prefix, term.group, term.slope) not in bindings:
                continue
            binding = bindings[(prefix, term.group, term.slope)]
            closed = varying[term.group][term.slope].reshape(ctx.total, -1)
            for index, recorded in enumerate(traces):
                if binding not in recorded.sites:
                    continue
                torch.testing.assert_close(
                    closed[index].double(),
                    recorded.sites[binding].value.reshape(-1).double(),
                    rtol=1e-5,
                    atol=1e-6,
                )
                checked += 1
    assert checked > 0, "no group coefficient binding was compared"


