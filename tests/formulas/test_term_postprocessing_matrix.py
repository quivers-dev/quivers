_FITS: dict[str, Fit] = {}


def fitted(name: str) -> Fit:
    """Fit one case once per worker process.

    Parameters
    ----------
    name : str
        Key of ``MODELS``.

    Returns
    -------
    BayesianFit or MultivariateFit
        The cached tiny fit.
    """
    if name not in _FITS:
        case = MODELS[name]
        options = dict(case.options)
        if options.pop("method", "svi") == "nuts":
            settings = {
                "method": "nuts",
                "num_warmup": 8,
                "num_samples": 20,
                "num_chains": 2,
                "control": {"max_treedepth": 3},
            }
        else:
            settings = {"method": "svi", "num_steps": 3}
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            if case.multiple:
                imputed = [case.data, case.data.assign(y=case.data.y + 0.1)]
                _FITS[name] = fit_multiple(
                    case.formula,
                    data=imputed,
                    seed=0,
                    **options,
                    **(settings | {"num_chains": 1}),
                ).pooled
            else:
                _FITS[name] = fit(
                    case.formula, data=case.data, seed=0, **options, **settings
                )
    return _FITS[name]


class Context:
    """A fitted case with the draw request every cell shares."""

    def __init__(self, name: str) -> None:
        self.name = name
        self.case = MODELS[name]
        self.fit = fitted(name)
        self.num_samples = DRAWS if self.case.method == "svi" else None
        self.shape = self.case.shape

    @property
    def draws(self) -> dict:
        """Return the draw-count keywords."""
        return {"num_samples": self.num_samples}

    @property
    def psis_draws(self) -> dict:
        """Return the draw-count keywords of a PSIS criterion."""
        return {"num_samples": PSIS_DRAWS if self.case.method == "svi" else None}

    @property
    def score(self) -> dict:
        """Return the response selection of information criteria."""
        resp = self.case.score_resp
        return {} if resp is None else {"resp": resp}

    @property
    def total(self) -> int:
        """Return the pooled draw count."""
        return self.shape[0] * self.shape[1]

    @property
    def responses(self) -> tuple[str, ...]:
        """Return the response labels of a joint fit."""
        return tuple(self.fit.response_names) if self.case.joint else ()


def _tensors(value) -> list[torch.Tensor]:
    """Collect every tensor inside a post-processing result."""
    if isinstance(value, torch.Tensor):
        return [value]
    if isinstance(value, np.ndarray):
        return [torch.as_tensor(value)]
    if isinstance(value, SummaryTable):
        return [value.values]
    if isinstance(value, Mapping):
        return [tensor for item in value.values() for tensor in _tensors(item)]
    if isinstance(value, (tuple, list)):
        return [tensor for item in value for tensor in _tensors(item)]
    if isinstance(value, pd.DataFrame):
        return [torch.as_tensor(value.select_dtypes("number").to_numpy(float))]
    if isinstance(value, (int, float)):
        return [torch.as_tensor(float(value))]
    return []


def finite(value, *, what: str) -> list[torch.Tensor]:
    """Assert a result holds at least one tensor and only finite numbers."""
    tensors = _tensors(value)
    assert tensors, f"{what} returned no numeric output: {type(value).__name__}"
    for tensor in tensors:
        assert bool(torch.isfinite(tensor.to(torch.float64)).all()), (
            f"{what} returned non-finite values"
        )
    return tensors


def per_response(value) -> list[torch.Tensor]:
    """Return a prediction result as one tensor per response."""
    if isinstance(value, Mapping):
        assert value, "empty prediction mapping"
        return list(value.values())
    return [value]


def check_draws(
    ctx: Context, value, rows: int | None, *, what: str, shape: tuple | None = None
) -> None:
    """Assert draws lie on (chain, draw, row, ...) axes and are finite."""
    finite(value, what=what)
    expected = ctx.shape if shape is None else shape
    for tensor in per_response(value):
        assert tuple(tensor.shape[:2]) == expected, (
            f"{what}: shape {tuple(tensor.shape)}, expected leading {expected}"
        )
        if rows is not None:
            assert tensor.shape[2] == rows, (
                f"{what}: shape {tuple(tensor.shape)}, expected {rows} rows"
            )


def check_table(table, rows: int | None, *, what: str) -> None:
    """Assert a summary table is finite with one row per unit."""
    tables = list(table.values()) if isinstance(table, Mapping) else [table]
    assert tables
    for item in tables:
        assert isinstance(item, SummaryTable), f"{what}: {type(item).__name__}"
        finite(item, what=what)
        if rows is not None:
            assert len(item.rows) == rows, f"{what}: {len(item.rows)} rows"


def _new(ctx: Context) -> dict:
    """Return the new-row keywords of a case."""
    return {"new_data": ctx.case.new, **ctx.case.new_options}


def _rows(ctx: Context, *, new: bool) -> int | None:
    """Return the expected row count of a prediction."""
    if new:
        return len(NEW_ROWS)
    return None if ctx.case.joint else ctx.case.rows


def cell_counts(ctx: Context) -> None:
    fit_ = ctx.fit
    assert fit_.nchains() == ctx.shape[0]
    assert fit_.ndraws(num_samples=ctx.num_samples) == ctx.total
    assert fit_.niterations() >= 1
    assert fit_.nwarmup() == (8 if ctx.case.method == "nuts" else 0)
    assert fit_.nvariables(**ctx.draws) == len(fit_.variables(**ctx.draws))
    if ctx.case.joint:
        assert all(fit_.nobs(resp=name) >= 19 for name in ctx.responses)
    else:
        assert fit_.nobs() == ctx.case.rows
    groups = fit_.ngrps()
    assert bool(groups) == ctx.case.groups
    assert all(count >= 2 for count in groups.values())


def cell_draws(ctx: Context) -> None:
    draws = ctx.fit.draws(**ctx.draws)
    assert draws
    finite(draws, what="draws")
    for site, value in draws.items():
        assert tuple(value.shape[:2]) == ctx.shape, site


#: Per-level and per-row variables, which the oracle omits.
_LEVEL_NAME = re.compile(
    r"^(r_|z_|s_|zs_|zgp_|rcar|zcar|nszcar|err\[|Ymi|Xme|zme|udf_|hs_local"
    r"|R2D2_phi|Cor_|lprior$|lp__$|Intercept$)"
)


def cell_variables(ctx: Context) -> None:
    names = ctx.fit.variables(**ctx.draws)
    assert names
    finite(names, what="variables")
    for name, value in names.items():
        assert tuple(value.shape) == ctx.shape, (
            f"variable {name!r} has shape {tuple(value.shape)}; every brms "
            f"variable is a scalar on {ctx.shape}"
        )
        assert "qvr" not in name.lower(), f"internal name leaked: {name!r}"
    if ctx.case.oracle is not None:
        expected = set(ORACLE[ctx.case.oracle]) - NOT_IN_QVR.get(ctx.case.oracle, set())
        mine = {name for name in names if not _LEVEL_NAME.match(name)} - QVR_ONLY.get(
            ctx.case.oracle, set()
        )
        assert mine == expected, (
            f"brms names differ: only here {sorted(mine - expected)}, "
            f"only brms {sorted(expected - mine)}"
        )
        # The shared names are in the order of brms's variables().
        assert [name for name in names if name in expected] == [
            name for name in ORACLE[ctx.case.oracle] if name in expected
        ]


#: brms variables without a QVR counterpart, by oracle key. Each entry is a
#: documented difference: brms's constant ``disc`` and the thresholds of an
#: ordinal family that QVR parameterizes as an intercept with offsets.
NOT_IN_QVR: dict[str, set[str]] = {
    "cumulative": {"disc"},
    "cs": {"disc", "b_Intercept[1]", "b_Intercept[2]", "b_Intercept[3]"},
}

#: QVR variables without a brms counterpart, by oracle key: the intercept
#: and offsets of non-cumulative ordinal thresholds, and the positive gap
#: that orders mixture intercepts.
QVR_ONLY: dict[str, set[str]] = {
    "cs": {"b_Intercept", "cutpoint_offset[1]", "cutpoint_offset[2]"},
    "mixture": {"mixture_intercept_spacing[1]"},
}


def cell_summary(ctx: Context) -> None:
    summary = ctx.fit.summary(**ctx.draws)
    tables = [
        table
        for table in (
            summary.fixed,
            summary.spec_pars,
            *summary.random.values(),
            summary.splines,
            summary.rescor,
            summary.other,
        )
        if table is not None
    ]
    assert tables
    columns = 4 if ctx.case.method == "svi" else 7
    for table in tables:
        finite(table, what="summary")
        assert len(table.columns) == columns
    named = [
        name
        for name in ctx.fit.variables(**ctx.draws)
        if not (name.startswith("r_") and name.endswith("]"))
    ]
    assert sum(len(table.rows) for table in tables) == len(named)
    robust = ctx.fit.summary(robust=True, mc_se=True, prob=0.8, **ctx.draws)
    assert robust.fixed is None or len(robust.fixed.columns) == columns + 1


