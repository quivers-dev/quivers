"""Cross product of model term types and public post-processing methods.

Each entry of ``MODELS`` is one tiny fitted model for a term, family or
option class of the formula interface. Each entry of ``CELLS`` exercises one
public post-processing method. Every (model, method) cell must either return
finite output of the documented shape or raise the located refusal declared
for it in ``ModelCase.refuse`` (a ``ValueError`` whose message is matched).
A bare ``TypeError``, ``KeyError``, ``RuntimeError`` or ``NotImplementedError``
fails the cell, and so does a declared refusal that does not occur.

Fits are cached per worker process. Where brms's ``variables()`` names are
pinned by ``oracles/brms_term_variables.json`` (generated by
``oracles/brms_term_variables.R``), the non-level names are compared.
"""

