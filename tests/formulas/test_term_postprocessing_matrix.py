class HyperbolicSecant(Distribution):
    """A hyperbolic secant law, absent from the native family registry."""

    arg_constraints = {"loc": constraints.real, "scale": constraints.positive}
    support = constraints.real
    has_rsample = True

    def __init__(self, loc: torch.Tensor, scale: torch.Tensor) -> None:
        self.loc, self.scale = torch.broadcast_tensors(loc, scale)
        super().__init__(self.loc.shape, validate_args=False)

    @property
    def mean(self) -> torch.Tensor:
        return self.loc

    @property
    def variance(self) -> torch.Tensor:
        return self.scale.square() * (math.pi / 2) ** 2

    def log_prob(self, value: torch.Tensor) -> torch.Tensor:
        z = (value - self.loc) / self.scale
        return math.log(2 / math.pi) - self.scale.log() - torch.logaddexp(z, -z)

    def rsample(self, sample_shape: torch.Size = torch.Size()) -> torch.Tensor:
        uniform = torch.rand(
            (*sample_shape, *self.batch_shape),
            dtype=self.loc.dtype,
            device=self.loc.device,
        )
        eps = torch.finfo(uniform.dtype).eps
        uniform = uniform.clamp(eps, 1 - eps)
        return self.loc + self.scale * (uniform * math.pi / 2).tan().log()

    def cdf(self, value: torch.Tensor) -> torch.Tensor:
        z = (value - self.loc) / self.scale
        tail = (2 / math.pi) * torch.atan(torch.exp(-z.abs()))
        return torch.where(z > 0, 1 - tail, tail)


def _secant_family():
    """Return a custom family over a catalog law with a data argument."""
    semantic = DistributionFamily(
        name="UserSecant",
        parameters=(
            FamilyParameter(name="center", constraint="real", rank=0),
            FamilyParameter(name="scale", constraint="positive", rank=0),
            FamilyParameter(name="bias", constraint="real", rank=0),
        ),
        support="real",
        element=REAL,
        event_rank=0,
        event_sources=(),
        discrete=False,
        reparameterizable=True,
        compositional=False,
    )
    catalog = FamilyCatalog().with_family(
        semantic,
        lambda parameters: HyperbolicSecant(
            parameters["center"] + parameters["bias"], parameters["scale"]
        ),
    )
    return custom_family(
        "UserSecant",
        catalog=catalog,
        location="center",
        auxiliary=(
            AuxParam(name="scale", prior="LogNormal(0.0, 0.3)", link=links["log"]),
        ),
        data={"bias": "known_bias"},
    )


class ModelCase:
    """One fitted model of the matrix.

    Parameters
    ----------
    formula : str or joint formula
        The model formula.
    options : Mapping
        ``fit`` keywords besides data and inference settings.
    method : {"svi", "nuts"}
        Inference method of the tiny fit.
    rows : int
        Expected number of model rows.
    groups : bool
        Whether the model has group-level effects.
    smooth : str or None
        A smooth or GP term label for ``conditional_smooths``.
    hypothesis : str or None
        A contrast over authored population labels (variable names for a
        joint fit), or None without one.
    hypothesis_options : Mapping
        Keywords of ``hypothesis`` selecting the contrast's parameter.
    residual : bool
        Whether the model has an unregressed residual ``sigma``, the
        ``residual__`` block of ``VarCorr``.
    categorical : bool
        Whether the response is ordinal or categorical.
    multicolumn : bool
        Whether each response row is a vector (multinomial, Dirichlet).
    missing_response : str
        The ``mi()`` response without recorded likelihood at ``missing_rows``.
    score_resp : str or None
        A response without missing values to score separately through ``resp``.
    missing_rows : tuple[int, ...]
        Training rows whose ``mi()`` response is missing and scores zero
        when evaluated alone.
    new_refusal : str or None
        Pattern of the documented refusal of every new-row prediction.
    splines : bool or None
        Whether the model has ``s()`` or ``t2()`` terms; read from a formula
        string when None.
    multiple : bool
        Fit two imputed datasets with ``fit_multiple`` and cross the pooled
        fit, the object brms's ``brm_multiple`` returns.
    epred_options : Mapping
        Keywords every conditional-mean call needs (``mc_samples``).
    effects_options : Mapping
        Further keywords of ``conditional_effects``.
    new_options : Mapping
        Keywords every new-row prediction needs (``data2``, ``trials``).
    refuse : Mapping[str, str]
        Cell name to the pattern of its documented located refusal.
    oracle : str or None
        Key of the pinned brms ``variables()`` names.
    """

    def __init__(
        self,
        formula,
        options: Mapping | None = None,
        *,
        method: str = "svi",
        rows: int = N,
        groups: bool = False,
        smooth: str | None = None,
        hypothesis: str | None = "x",
        hypothesis_options: Mapping | None = None,
        residual: bool = True,
        categorical: bool = False,
        multicolumn: bool = False,
        missing_rows: tuple[int, ...] = (),
        missing_response: str = "ymis",
        score_resp: str | None = None,
        new_refusal: str | None = None,
        multiple: bool = False,
        splines: bool | None = None,
        epred_options: Mapping | None = None,
        effects_options: Mapping | None = None,
        new_options: Mapping | None = None,
        refuse: Mapping[str, str] | None = None,
        oracle: str | None = None,
        data: pd.DataFrame | None = None,
    ) -> None:
        self.formula = formula
        self.options = dict(options or {})
        self.method = method
        self.rows = rows
        self.groups = groups
        self.smooth = smooth
        self.hypothesis = hypothesis
        self.hypothesis_options = dict(hypothesis_options or {})
        self.residual = residual
        self.categorical = categorical
        self.multicolumn = multicolumn
        self.missing_rows = missing_rows
        self.missing_response = missing_response
        self.score_resp = score_resp
        self.new_refusal = new_refusal
        self.multiple = multiple
        self.splines = (
            isinstance(formula, str)
            and re.search(r"(^|[^A-Za-z0-9_.])(s|t2)\(", formula) is not None
            if splines is None
            else splines
        )
        self.epred_options = dict(epred_options or {})
        self.effects_options = dict(effects_options or {})
        self.new_options = dict(new_options or {})
        self.refuse = dict(refuse or {})
        self.oracle = oracle
        self.data = DATA if data is None else data

    @property
    def joint(self) -> bool:
        """Report whether the case fits a joint formula."""
        return not isinstance(self.formula, str) and not hasattr(
            self.formula, "formula"
        )

    @property
    def shape(self) -> tuple[int, int]:
        """Return the (chain, draw) shape every cell requests."""
        return (1, DRAWS) if self.method == "svi" else (2, 20)

    @property
    def new(self) -> pd.DataFrame:
        """Return the new rows of the case."""
        return self.data.iloc[list(NEW_ROWS)].copy()


