"""brms grouping-term syntax: ``gr()``, ``g1:g2``, ``g1/g2``, bars, and shared IDs.

The oracle ``oracles/brms_grouping.json`` is generated by
``oracles/brms_grouping.R`` from brms's ``make_standata``, ``make_stancode``,
and ``get_prior``.
"""

import json
import pathlib
import re
from typing import Literal

import numpy as np
import pandas as pd
import pytest
import torch

from quivers.continuous.programs import MonadicProgram
from quivers.dsl import Compiler
from quivers.dsl.emit import module_to_source
from quivers.formulas import (
    FormulaToQVRModule,
    GroupCovariance,
    families,
    fit,
    formula_from_data,
)
from quivers.formulas._fit import BayesianFit
from quivers.inference.trace import trace
from quivers.modeling import load_fit, save_fit

ORACLE = json.loads(
    (pathlib.Path(__file__).parent / "oracles" / "brms_grouping.json").read_text()
)


def _program(module):
    """Compile a module to its native monadic program."""
    program = Compiler(module).compile().morphism
    assert isinstance(program, MonadicProgram)
    return program


def _scale(text: str) -> float:
    """Read the scale argument of a canonical prior call."""
    match = re.search(r"scale=([0-9.e-]+)", text)
    assert match is not None
    return float(match.group(1))


def _fit_with(
    method: Literal["svi", "hmc", "nuts"], formula: str, frame: pd.DataFrame, **extra
) -> BayesianFit:
    """Fit with a tiny run of one inference method."""
    if method == "svi":
        return fit(formula, data=frame, method="svi", num_steps=3, seed=2, **extra)
    return fit(
        formula,
        data=frame,
        method=method,
        num_warmup=2,
        num_samples=2,
        num_chains=1,
        seed=2,
        **extra,
    )


def _restored(path: pathlib.Path) -> BayesianFit:
    """Load a saved formula fit."""
    restored = load_fit(path)
    assert isinstance(restored, BayesianFit)
    return restored


def _oracle_frame() -> pd.DataFrame:
    return pd.DataFrame(ORACLE["data"])


def _covariance() -> pd.DataFrame:
    labels = ["u", "v", "w"]
    return pd.DataFrame(
        [[1.0, 0.5, 0.2], [0.5, 2.0, 0.3], [0.2, 0.3, 1.5]],
        index=labels,
        columns=labels,
    )


def _forward(text: str, **options) -> tuple:
    formula = formula_from_data(text, _oracle_frame())
    lens = FormulaToQVRModule(families["gaussian"], **options)
    module, _ = lens.forward(formula)
    return formula, lens, module


@pytest.mark.parametrize("case", ORACLE["cases"], ids=lambda case: case["formula"])
def test_grouping_codes_and_labels_match_brms(case):
    formula = formula_from_data(case["formula"], _oracle_frame())
    groups = list(dict.fromkeys(row["group"] for row in case["sd"]))
    for block, group in enumerate(groups):
        codes = np.asarray(case["J"][f"J_{block + 1}"]) - 1
        np.testing.assert_array_equal(formula.group_indices[group], codes)
        assert len(formula.group_levels[group]) == case["N"][f"N_{block + 1}"]
    assert [(term.slope, term.group) for term in formula.random_terms] == [
        (row["coef"], row["group"]) for row in case["sd"]
    ]
    correlated = {term.group for term in formula.random_terms if term.correlation_id}
    blocks = {
        (term.group, term.correlation_id)
        for term in formula.random_terms
        if term.correlation_id
    }
    # brms reports a cor class exactly for blocks of more than one coefficient.
    multiple = {
        group
        for group, identity in blocks
        if sum(
            term.group == group and term.correlation_id == identity
            for term in formula.random_terms
        )
        > 1
    }
    assert multiple == set(
        case["cor"] if isinstance(case["cor"], list) else [case["cor"]]
    )
    assert multiple <= correlated


def test_interaction_levels_paste_source_labels_as_brms():
    formula = formula_from_data("y ~ (1 | g1:g2)", _oracle_frame())
    assert formula.group_levels["g1:g2"] == ("a_u", "a_v", "a_w", "b_u", "b_v", "b_w")


@pytest.mark.parametrize(
    ("authored", "equivalent"),
    [
        ("y ~ (1 + x | gr(g2, cor = FALSE))", "y ~ (1 + x || g2)"),
        ("y ~ (1 + x | gr(g2))", "y ~ (1 + x | g2)"),
        (
            "y ~ (1 | gr(g2, id = 'i')) + (0 + x | gr(g2, id = 'i'))",
            "y ~ (1 |i| g2) + (0 + x |i| g2)",
        ),
        ("y ~ (1 | g1/g2)", "y ~ (1 | g1) + (1 | g1:g2)"),
    ],
)
def test_gr_options_emit_the_same_program_as_bar_notation(authored, equivalent):
    assert module_to_source(_forward(authored)[2]) == module_to_source(
        _forward(equivalent)[2]
    )


def test_gr_cov_uses_the_data2_covariance_as_brms_lcov():
    case = next(c for c in ORACLE["cases"] if "cov" in c["formula"])
    lcov = torch.tensor(case["Lcov"], dtype=torch.float64)
    frame = _oracle_frame()
    priors = fit(
        "y ~ (1 | gr(g2, cov = A))",
        data=frame,
        data2={"A": _covariance()},
        method="svi",
        num_steps=1,
        seed=1,
    )
    covariance = priors.group_covariances["g2"].tensor()
    torch.testing.assert_close(covariance, lcov @ lcov.T)
    supplied = GroupCovariance(levels=("u", "v", "w"), matrix=lcov @ lcov.T)
    by_option = _forward("y ~ (1 | g2)", group_covariances={"g2": supplied})[2]
    by_data2 = FormulaToQVRModule(
        families["gaussian"], group_covariances=priors.group_covariances
    ).forward(formula_from_data("y ~ (1 | g2)", frame))[0]
    assert module_to_source(by_option) == module_to_source(by_data2)
    # The emitted factor reproduces brms's sd * Lcov * z law.
    lens = FormulaToQVRModule(families["gaussian"], group_covariances={"g2": supplied})
    formula = formula_from_data("y ~ (1 | g2)", frame)
    lens.forward(formula)
    factor = lens.fixed_column_observations(formula)["__formula_level_basis_g2_factor"]
    torch.testing.assert_close(factor @ factor.T, lcov @ lcov.T)


def test_unsupported_and_invalid_grouping_terms_are_refused():
    frame = _oracle_frame()
    with pytest.raises(ValueError, match="multiple blocks"):
        formula_from_data("y ~ (1 | g1) + (x | g1)", frame)
    assert "Duplicated group-level effects" in ORACLE["duplicate"]
    with pytest.raises(ValueError, match="dist must be 'gaussian' or 'student'"):
        formula_from_data("y ~ (1 | gr(g2, dist = 'cauchy'))", frame)
    with pytest.raises(ValueError, match="single grouping term"):
        formula_from_data("y ~ (1 | gr(g1, g2))", frame)
    with pytest.raises(ValueError, match="must be a column name"):
        formula_from_data("y ~ (1 | log(g2))", frame)
    with pytest.raises(ValueError, match="requires data2"):
        fit("y ~ (1 | gr(g2, cov = A))", data=frame, method="svi", num_steps=1)
    with pytest.raises(ValueError, match="labeled pandas DataFrame"):
        fit(
            "y ~ (1 | gr(g2, cov = A))",
            data=frame,
            data2={"A": _covariance().to_numpy()},
            method="svi",
            num_steps=1,
        )


def _frame(rows: int = 36) -> pd.DataFrame:
    generator = np.random.default_rng(17)
    frame = pd.DataFrame(
        {
            "x": generator.normal(size=rows),
            "g1": np.array(["a", "b", "c"])[np.arange(rows) % 3],
            "g2": np.array(["u", "v", "w"])[(np.arange(rows) // 3) % 3],
        }
    )
    frame["y"] = 0.4 * frame["x"] + generator.normal(scale=0.5, size=rows)
    return frame


FORMULA = "y ~ x + (1 | g1/g2) + (1 + x | gr(g2, cov = A, cor = FALSE))"


@pytest.mark.parametrize("method", ["svi", "hmc", "nuts"])
def test_every_inference_method_predicts_new_and_unseen_combinations(method):
    fitted = _fit_with(method, FORMULA, _frame(), data2={"A": _covariance()})
    fresh = pd.DataFrame({"x": [0.1, -0.5], "g1": ["a", "c"], "g2": ["w", "u"]})
    draws = fitted.posterior_epred(new_data=fresh, num_samples=2, seed=5)
    assert draws.shape[-1] == 2 and torch.isfinite(draws).all()
    unseen = fresh.assign(g1=["d", "a"])
    with pytest.raises(ValueError, match="allow_new_levels"):
        fitted.posterior_epred(new_data=unseen, num_samples=1)
    draws = fitted.posterior_predict(
        new_data=unseen, num_samples=2, seed=5, allow_new_levels=True
    )
    assert torch.isfinite(draws).all()


def test_training_rows_reproduce_and_artifact_round_trips(tmp_path):
    frame = _frame()
    fitted = fit(
        FORMULA,
        data=frame,
        data2={"A": _covariance()},
        method="svi",
        num_steps=2,
        seed=3,
    )
    torch.testing.assert_close(
        fitted.posterior_linpred(new_data=frame, num_samples=3, seed=4),
        fitted.posterior_linpred(num_samples=3, seed=4),
    )
    refit = fitted.update(data=frame.iloc[:27].reset_index(drop=True))
    assert refit.group_covariances.keys() == {"g2"}
    fresh = pd.DataFrame({"x": [0.1, -0.5], "g1": ["a", "c"], "g2": ["w", "u"]})
    expected = fitted.posterior_epred(new_data=fresh, num_samples=2, seed=9)
    path = tmp_path / "grouping.qfit"
    save_fit(fitted, path)
    restored = _restored(path)
    assert restored.formula.grouping == fitted.formula.grouping
    torch.testing.assert_close(
        restored.posterior_epred(new_data=fresh, num_samples=2, seed=9), expected
    )


def test_independent_coefficients_follow_a_supplied_covariance():
    # Each coefficient of (1 + x || g2) is sigma * F u with F F^T = K, the law
    # brms gives every coefficient of gr(g2, cov = K, cor = FALSE).
    covariance = torch.tensor(_covariance().to_numpy())
    supplied = GroupCovariance(levels=("u", "v", "w"), matrix=covariance)
    formula, lens, module = _forward(
        "y ~ (1 + x || g2)", group_covariances={"g2": supplied}
    )
    program = _program(module)
    values = dict(lens.fixed_column_observations(formula))
    values["y"] = torch.as_tensor(formula.response_values.copy())
    values["g2_idx"] = torch.tensor(formula.group_indices["g2"], dtype=torch.long)
    factor = values["__formula_level_basis_g2_factor"]
    torch.testing.assert_close(factor @ factor.T, covariance)
    generator = torch.Generator().manual_seed(2)
    raw = {}
    for slope, scale in (("Intercept", 0.7), ("x", 1.3)):
        raw[slope] = torch.randn(3, 1, generator=generator, dtype=torch.float64)
        values[f"sigma_g2_{slope}"] = torch.tensor(scale, dtype=torch.float64)
        values[f"group_covariance_independent_g2_{slope}"] = raw[slope]
    values["intercept"] = torch.tensor(0.0, dtype=torch.float64)
    values["sigma"] = torch.tensor(1.0, dtype=torch.float64)
    sites = trace(program, torch.zeros(1, 1), values).sites
    torch.testing.assert_close(
        sites["alpha_g2"].value.reshape(-1),
        0.7 * (factor @ raw["Intercept"]).reshape(-1),
    )
    torch.testing.assert_close(
        sites["beta_g2_x"].value.reshape(-1), 1.3 * (factor @ raw["x"]).reshape(-1)
    )


def test_re_formula_selects_terms_written_with_grouping_syntax():
    frame = _frame()
    frame["h"] = np.array(["p", "q", "r", "s"])[np.arange(len(frame)) % 4]
    fitted = fit(
        "y ~ x + (1 | g1/g2) + (1 | mm(g2, h))",
        data=frame,
        method="svi",
        num_steps=2,
        seed=5,
    )
    fresh = frame.iloc[:4]
    everything = fitted.posterior_linpred(new_data=fresh, num_samples=2, seed=1)
    nested = fitted.posterior_linpred(
        new_data=fresh, num_samples=2, seed=1, re_formula="~ (1 | g1/g2)"
    )
    membership = fitted.posterior_linpred(
        new_data=fresh, num_samples=2, seed=1, re_formula="~ (1 | mm(g2, h))"
    )
    none = fitted.posterior_linpred(
        new_data=fresh, num_samples=2, seed=1, re_formula="~0"
    )
    # Group contributions are additive: the two selections partition all effects.
    torch.testing.assert_close(nested + membership - none, everything)
    with pytest.raises(ValueError, match="unfitted term"):
        fitted.posterior_linpred(
            new_data=fresh, num_samples=1, re_formula="~ (1 | mm(h, g2))"
        )
