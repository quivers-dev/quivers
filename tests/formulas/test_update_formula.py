"""``update(formula=...)`` follows R's ``update.formula``.

The expected formulas are the output of R's ``update.formula``, generated by
``oracles/update_formula_oracle.R`` and pinned here. Refits are checked by
their population and group-level coefficient names.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from quivers.formulas import fit, fit_multiple
from quivers.formulas._formula_options import expand_dot_formula

R_UPDATE_FORMULA = [
    ("y ~ x + z", ". ~ . + w", "y ~ x + z + w"),
    ("y ~ x + z", ". ~ . - z", "y ~ x"),
    ("y ~ x", "log(.) ~ .", "log(y) ~ x"),
    ("y ~ x", "y2 ~ z", "y2 ~ z"),
    ("y ~ x + (1 | g)", ". ~ . + w", "y ~ x + (1 | g) + w"),
    ("y ~ x + (1 | g) + (1 | h)", ". ~ . + w", "y ~ x + (1 | g) + (1 | h) + w"),
    ("y ~ x + (1 | g)", "~ . + w", "y ~ x + (1 | g) + w"),
    ("y ~ x + (1 | g)", ". ~ . - (1 | g)", "y ~ x"),
    ("y ~ x + (1 | g)", ". ~ . - x", "y ~ (1 | g)"),
    ("y ~ x + (1 + x | g)", ". ~ . - (1 + x | g) + (1 | g)", "y ~ x + (1 | g)"),
    ("y ~ x + z", ". ~ . + x", "y ~ x + z"),
    ("y ~ x", ". ~ . - x", "y ~ 1"),
    ("y ~ x + z", ". ~ . - 1", "y ~ x + z - 1"),
    ("y ~ x + z", ". ~ . + 0", "y ~ x + z - 1"),
    ("y ~ 0 + x", ". ~ . + 1", "y ~ x"),
    ("y ~ x + z", ". ~ w + .", "y ~ w + x + z"),
    ("y ~ x + s(z)", ". ~ . + w", "y ~ x + s(z) + w"),
    ("y ~ x + z", ". ~ . - (x + z) + w", "y ~ w"),
    ("y ~ x + (1 | g)", ". ~ . + (1 | h)", "y ~ x + (1 | g) + (1 | h)"),
    ("y ~ x + z", "sqrt(.) ~ . - z + w", "sqrt(y) ~ x + w"),
    ("y ~ x - 1", ". ~ . + w", "y ~ x + w - 1"),
    ("y ~ x + I(z - 1)", ". ~ . - I(z - 1)", "y ~ x"),
]
"""``(old, new, update.formula(old, new))`` as printed by R."""


@pytest.mark.parametrize(("old", "new", "expected"), R_UPDATE_FORMULA)
def test_dot_updates_match_r_update_formula(old: str, new: str, expected: str) -> None:
    assert expand_dot_formula(old, new) == expected


def test_terms_are_matched_without_regard_to_spacing() -> None:
    assert expand_dot_formula("y ~ x + (1|g)", ". ~ . - (1 | g)") == "y ~ x"
    assert expand_dot_formula("y ~ x + s(z, k=4)", ". ~ . - s(z, k = 4)") == "y ~ x"
    # Signs inside a call, an exponent, or after an operator stay in the term.
    assert (
        expand_dot_formula("y ~ I(x - 1) + offset(1e-3 * z)", ". ~ . + w")
        == "y ~ I(x - 1) + offset(1e-3 * z) + w"
    )
    assert expand_dot_formula("y ~ x", ". ~ . + I(z ** -1)") == "y ~ x + I(z ** -1)"


def test_an_interaction_removal_is_left_to_the_formula_algebra() -> None:
    # R prints y ~ x + z + w + x:z and y ~ x + z; the unexpanded spelling
    # denotes the same terms.
    assert expand_dot_formula("y ~ x * z", ". ~ . + w") == "y ~ x * z + w"
    assert expand_dot_formula("y ~ x * z", ". ~ . - x:z") == "y ~ x * z - x:z"


def test_rejected_updates_name_the_problem() -> None:
    with pytest.raises(ValueError, match="has no '~'"):
        expand_dot_formula("y ~ x", ". + w")
    with pytest.raises(ValueError, match="dot on the left"):
        expand_dot_formula("~ x", "log(.) ~ .")
    with pytest.raises(ValueError, match="group-level terms"):
        expand_dot_formula("y ~ x + (1 | g)", ". ~ .:w")
    with pytest.raises(ValueError, match="unbalanced parentheses"):
        expand_dot_formula("y ~ x", ". ~ . + (w")
    with pytest.raises(ValueError, match="ends without a term"):
        expand_dot_formula("y ~ x", ". ~ . +")
    # Without group-level terms the dot keeps R's parenthesized substitution.
    assert expand_dot_formula("y ~ x + z", ". ~ .:w") == "y ~ (x + z):w"


def _frame(seed: int = 0, n: int = 24) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    rows = np.arange(n)
    frame = pd.DataFrame(
        {
            "x": np.sin(rows * 0.7),
            "w": 1.0 + (rows % 3) * 0.5,
            "g": np.array(["a", "b", "c", "d"])[rows % 4],
            "h": np.array(["p", "q", "r"])[(rows // 4) % 3],
        }
    )
    frame["y"] = 1.0 + 0.5 * frame.x + 0.3 * rng.standard_normal(n)
    return frame


def _names(fitted) -> tuple[list[str], list[str]]:
    variables = list(fitted.variables(num_samples=2))
    return (
        [name for name in variables if name.startswith("b_")],
        sorted(name for name in variables if name.startswith("sd_")),
    )


@pytest.mark.parametrize(
    ("formula", "groups"),
    [
        ("y ~ x + (1 | g)", ["sd_g__Intercept"]),
        ("y ~ x + (1 | g) + (1 | h)", ["sd_g__Intercept", "sd_h__Intercept"]),
    ],
)
def test_update_keeps_group_terms_when_adding_a_predictor(
    formula: str, groups: list[str]
) -> None:
    fitted = fit(formula, data=_frame(), method="svi", num_steps=2, seed=1)
    assert _names(fitted) == (["b_Intercept", "b_x"], groups)
    for spelling in (". ~ . + w", "~ . + w"):
        grown = fitted.update(formula=spelling)
        assert _names(grown) == (["b_Intercept", "b_x", "b_w"], groups)
        assert grown.nobs() == fitted.nobs()


def test_update_removes_and_replaces_group_terms() -> None:
    fitted = fit(
        "y ~ x + (1 + x | g)", data=_frame(), method="svi", num_steps=2, seed=1
    )
    assert _names(fitted)[1] == ["sd_g__Intercept", "sd_g__x"]
    assert _names(fitted.update(formula=". ~ . - (1 + x | g)")) == (
        ["b_Intercept", "b_x"],
        [],
    )
    replaced = fitted.update(formula=". ~ . - (1 + x | g) + (1 | h) - x")
    assert _names(replaced) == (["b_Intercept"], ["sd_h__Intercept"])


def test_multiple_fit_update_accepts_a_dot_formula_with_group_terms() -> None:
    datasets = [_frame(seed) for seed in (0, 1)]
    fitted = fit_multiple(
        "y ~ x + (1 | g)",
        data=datasets,
        num_warmup=3,
        num_samples=3,
        num_chains=1,
        control={"max_treedepth": 3},
        seed=1,
    )
    grown = fitted.update(datasets, formula=". ~ . + w")
    assert len(grown.fits) == 2
    for member in grown.fits:
        assert _names(member) == (["b_Intercept", "b_x", "b_w"], ["sd_g__Intercept"])
