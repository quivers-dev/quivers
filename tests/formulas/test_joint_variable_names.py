"""Joint fits name coefficients with brms's renaming, as single fits do.

The oracle is ``tests/formulas/oracles/brms_joint_variable_names.json``,
generated by ``brms_joint_variable_names.R`` beside it: ``variables()`` of a
brms 2.20.4 joint model with factor levels, an interaction, ``I(x^2)``, a
distributional predictor and a factor varying slope.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import cast

import pandas as pd
import pytest
import torch

from quivers.formulas import bf, fit, set_rescor
from quivers.formulas._joint_fit import MultivariateFit
from quivers.formulas._multivariate import MultivariateFormula
from quivers.formulas._postprocess_names import brms_rename

ORACLE = json.loads(
    (Path(__file__).parent / "oracles" / "brms_joint_variable_names.json").read_text()
)
FRAME = pd.DataFrame(ORACLE["data"])


def _joint() -> MultivariateFit:
    fitted = fit(
        cast(
            MultivariateFormula,
            bf("y ~ x * f + (1 + f | g)")
            + bf("y2 ~ I(x^2) + h", "sigma ~ f")
            + set_rescor(False),
        ),
        data=FRAME,
        method="svi",
        num_steps=5,
        seed=1,
    )
    assert isinstance(fitted, MultivariateFit)
    return fitted


def test_joint_variables_equal_brms_names():
    named = _joint().variables(num_samples=3)
    # Names and their order are brms's variables().
    assert list(named) == ORACLE["variables"]
    # The design labels themselves are not brms names.
    assert {"b_y_f", "b_y_x:f", "b_y2_h_1", "sd_g__y_f"}.isdisjoint(named)


def test_renamed_variables_hold_the_native_draws(monkeypatch: pytest.MonkeyPatch):
    fitted = _joint()
    draws = fitted.draws(num_samples=3)

    def rebuild(*_args):
        raise AssertionError("naming a joint draw must not compile a response fit")

    monkeypatch.setattr(MultivariateFit, "_response_fit", rebuild)
    named = fitted.variables(num_samples=3)
    assert torch.equal(named["b_y_fq"], draws["response_y__beta_f"])
    assert torch.equal(named["b_y_x:fq"], draws["response_y__beta_x_f"])
    assert torch.equal(named["b_y2_IxE2"], draws["response_y2__beta_I_x_2"])
    assert torch.equal(named["b_sigma_y2_fq"], draws["response_y2__dpar_sigma_beta_f"])
    assert torch.equal(named["sd_g__y_fq"], draws["response_y__sigma_g_f"])


def test_single_fits_use_the_same_labels():
    single = fit("y2 ~ I(x^2) + h", data=FRAME, method="svi", num_steps=5, seed=1)
    assert {"b_Intercept", "b_IxE2", "b_hv", "b_hw"} <= set(
        single.variables(num_samples=2)
    )
    assert brms_rename("I(x^2)") == "IxE2"
