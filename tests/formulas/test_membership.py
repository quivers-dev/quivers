ORACLE = json.loads(
    (pathlib.Path(__file__).parent / "oracles" / "brms_membership.json").read_text()
)


def _program(module):
    """Compile a module to its native monadic program."""
    program = Compiler(module).compile().morphism
    assert isinstance(program, MonadicProgram)
    return program


def _scale(text: str) -> float:
    """Read the scale argument of a canonical prior call."""
    match = re.search(r"scale=([0-9.e-]+)", text)
    assert match is not None
    return float(match.group(1))


def _fit_with(
    method: Literal["svi", "hmc", "nuts"], formula: str, frame: pd.DataFrame, **extra
) -> BayesianFit:
    """Fit with a tiny run of one inference method."""
    if method == "svi":
        return fit(formula, data=frame, method="svi", num_steps=3, seed=2, **extra)
    return fit(
        formula,
        data=frame,
        method=method,
        num_warmup=2,
        num_samples=2,
        num_chains=1,
        seed=2,
        **extra,
    )


def _restored(path: pathlib.Path) -> BayesianFit:
    """Load a saved formula fit."""
    restored = load_fit(path)
    assert isinstance(restored, BayesianFit)
    return restored


# Weighted sums of a few float64 products of order one.
RTOL, ATOL = 1e-12, 1e-12


def _oracle_frame() -> pd.DataFrame:
    return pd.DataFrame(ORACLE["data"])


def _as_list(value):
    return value if isinstance(value, list) else [value]


@pytest.mark.parametrize("case", ORACLE["cases"], ids=lambda case: case["formula"])
def test_codes_weights_covariates_and_labels_match_brms(case):
    formula = formula_from_data(case["formula"], _oracle_frame())
    data = case["data"]
    [group] = set(_as_list(case["group"]))
    [membership] = formula.grouping.memberships
    assert membership.group == group
    assert len(formula.group_levels[group]) == int(data["N_1"])
    blocks = sorted({key.split("_")[1] for key in data if key.startswith("J_")})
    for block in blocks:
        for k in range(membership.size):
            np.testing.assert_array_equal(
                np.asarray(membership.codes[k]) + 1, data[f"J_{block}_{k + 1}"]
            )
            np.testing.assert_allclose(
                membership.weights[:, k],
                data[f"W_{block}_{k + 1}"],
                rtol=RTOL,
                atol=ATOL,
            )
    # brms's Z_<block>_<coef>_<member>, in brms's coefficient order.
    brms_coefficients = []
    for block in blocks:
        coefficients = sorted(
            {int(key.split("_")[2]) for key in data if key.startswith(f"Z_{block}_")}
        )
        brms_coefficients.extend((block, c) for c in coefficients)
    terms = [term for term in formula.random_terms if term.group == group]
    assert len(terms) == len(brms_coefficients)
    for term, (block, coefficient) in zip(terms, brms_coefficients, strict=True):
        covariate = formula.grouping.covariate(group, term.slope)
        assert covariate is not None
        for k in range(membership.size):
            np.testing.assert_allclose(
                covariate.values[:, k],
                data[f"Z_{block}_{coefficient}_{k + 1}"],
                rtol=RTOL,
                atol=ATOL,
            )
    labels = {re.sub(r"[ ()]|,", "", term.slope) for term in terms}
    assert labels == set(_as_list(case["sd"]))


_MEMBER = re.compile(
    r"W_(\d+)_(\d+)\[n\] \* r_(\d+)_(\d+)\[J_\d+_\d+\[n\]\] \* Z_(\d+)_(\d+)_(\d+)\[n\]"
)


def _brms_predictor(case, effects):
    """Evaluate brms's generated Stan expression with brms's own data."""
    data = case["data"]
    rows = len(ORACLE["data"])
    mu = np.zeros(rows)
    for block, member, r_block, r_coef, z_block, z_coef, z_member in _MEMBER.findall(
        case["predictor"]
    ):
        codes = np.asarray(data[f"J_{block}_{member}"], dtype=int) - 1
        mu += (
            np.asarray(data[f"W_{block}_{member}"])
            * effects[(r_block, r_coef)][codes]
            * np.asarray(data[f"Z_{z_block}_{z_coef}_{z_member}"])
        )
    return mu


@pytest.mark.parametrize(
    "case",
    # Independent coefficients: each is sigma * z with sites named by slope.
    [case for case in ORACLE["cases"] if "mmc(x1, x2) | mm" not in case["formula"]],
    ids=lambda case: case["formula"],
)
def test_emitted_predictor_equals_brms_generated_stan_expression(case):
    formula = formula_from_data(case["formula"], _oracle_frame())
    lens = FormulaToQVRModule(families["gaussian"])
    module, _ = lens.forward(formula)
    program = _program(module)
    values = dict(lens.fixed_column_observations(formula))
    values["y"] = torch.as_tensor(formula.response_values.copy())
    for group, codes in formula.group_indices.items():
        values[f"{_qvr_name(group)}_idx"] = torch.tensor(codes, dtype=torch.long)
    group = formula.grouping.memberships[0].group
    levels = len(formula.group_levels[group])
    generator = np.random.default_rng(5)
    order = []
    for _, _, r_block, r_coef, *_ in _MEMBER.findall(case["predictor"]):
        if (r_block, r_coef) not in order:
            order.append((r_block, r_coef))
    effects = {key: generator.normal(size=levels) for key in order}
    terms = [term for term in formula.random_terms if term.group == group]
    for term, key in zip(terms, order, strict=True):
        name = f"{_qvr_name(group)}_{_qvr_name(term.slope)}"
        values[f"sigma_{name}"] = torch.tensor(1.0, dtype=torch.float64)
        values[f"z_{name}"] = torch.as_tensor(effects[key])
    values["intercept"] = torch.tensor(0.0, dtype=torch.float64)
    values["sigma"] = torch.tensor(1.0, dtype=torch.float64)
    result = trace(program, torch.zeros(1, 1), values)
    eta = result.sites["eta"].value.reshape(-1).detach().numpy()
    np.testing.assert_allclose(
        eta, _brms_predictor(case, effects), rtol=RTOL, atol=ATOL
    )


def test_joint_density_and_derivatives_match_hand_written_oracle():
    frame = _oracle_frame()
    text = "y ~ x1 + (1 + x1 || mm(g1, g2, weights = cbind(w1, w2)))"
    formula = formula_from_data(text, frame)
    lens = FormulaToQVRModule(families["gaussian"])
    module, _ = lens.forward(formula)
    program = _program(module)
    observed = dict(lens.fixed_column_observations(formula))
    observed["y"] = torch.as_tensor(formula.response_values.copy())
    for group, codes in formula.group_indices.items():
        observed[f"{_qvr_name(group)}_idx"] = torch.tensor(codes, dtype=torch.long)
    beta_scale = _scale(get_prior(text, data=frame)["beta_x1"])
    levels = sorted(set(frame["g1"]) | set(frame["g2"]))
    position = {label: index for index, label in enumerate(levels)}
    j1 = torch.tensor([position[v] for v in frame["g1"]])
    j2 = torch.tensor([position[v] for v in frame["g2"]])
    w = torch.as_tensor(frame[["w1", "w2"]].to_numpy(dtype=float))
    w = w / w.sum(1, keepdim=True)
    x1 = torch.tensor(frame["x1"].to_numpy(dtype=float))
    y = observed["y"]
    count = len(levels)

    def split(point):
        return (
            point[0],
            point[1],
            point[2],
            point[3 : 3 + count],
            point[3 + count],
            point[4 + count : 4 + 2 * count],
            point[4 + 2 * count],
        )

    def actual(point):
        intercept, beta, sd0, z0, sd1, z1, sigma = split(point)
        values = {
            **observed,
            "intercept": intercept,
            "beta_x1": beta,
            "sigma_mmg1g2_Intercept": sd0,
            "z_mmg1g2_Intercept": z0,
            "sigma_mmg1g2_x1": sd1,
            "z_mmg1g2_x1": z1,
            "sigma": sigma,
        }
        joint = trace(program, point.new_zeros(1, 1), values).log_joint
        assert joint is not None
        return joint.sum()

    def oracle(point):
        intercept, beta, sd0, z0, sd1, z1, sigma = split(point)
        r0, r1 = sd0 * z0, sd1 * z1
        mu = intercept + beta * x1
        for k, codes in enumerate((j1, j2)):
            mu = mu + w[:, k] * (r0[codes] + r1[codes] * x1)
        normal = torch.distributions.Normal
        return (
            normal(0.0, 5.0).log_prob(intercept)
            + normal(0.0, beta_scale).log_prob(beta)
            + torch.distributions.HalfNormal(1.0).log_prob(sd0)
            + torch.distributions.HalfNormal(1.0).log_prob(sd1)
            + normal(0.0, 1.0).log_prob(z0).sum()
            + normal(0.0, 1.0).log_prob(z1).sum()
            + torch.distributions.HalfCauchy(2.0).log_prob(sigma)
            + normal(mu, sigma).log_prob(y).sum()
        )

    generator = torch.Generator().manual_seed(4)
    point = 0.5 * torch.randn(5 + 2 * count, generator=generator, dtype=torch.float64)
    for index in (2, 3 + count, 4 + 2 * count):
        point[index] = 0.8 + 0.1 * index / count
    point.requires_grad_()
    torch.testing.assert_close(actual(point), oracle(point))
    torch.testing.assert_close(
        torch.autograd.functional.jacobian(actual, point),
        torch.autograd.functional.jacobian(oracle, point),
    )
    torch.testing.assert_close(
        torch.autograd.functional.hessian(actual, point),
        torch.autograd.functional.hessian(oracle, point),
    )


def test_invalid_memberships_are_refused():
    frame = _oracle_frame()
    with pytest.raises(ValueError, match="at least two grouping variables"):
        formula_from_data("y ~ (1 | mm(g1))", frame)
    with pytest.raises(
        ValueError, match="negative membership weights require scale=False"
    ):
        formula_from_data(
            "y ~ (1 | mm(g1, g2, weights = cbind(w1, n)))", frame.assign(n=-1.0)
        )
    with pytest.raises(ValueError, match="as many columns as grouping terms"):
        formula_from_data("y ~ (1 | mm(g1, g2, weights = cbind(w1)))", frame)
    with pytest.raises(ValueError, match="mmc\\(\\) requires an mm\\(\\) grouping"):
        formula_from_data("y ~ (1 + mmc(x1, x2) | g1)", frame)
    with pytest.raises(ValueError, match="one covariate per member"):
        formula_from_data("y ~ (1 + mmc(x1, x2, y) | mm(g1, g2))", frame)
    with pytest.raises(ValueError, match="unknown arguments"):
        formula_from_data("y ~ (1 | mm(g1, g2, wieghts = cbind(w1, w2)))", frame)
    # As brms's na_omit, a row missing a member is removed, not refused.
    with pytest.warns(UserWarning, match=r"\['m'\]"):
        dropped = formula_from_data(
            "y ~ (1 | mm(g1, m))", frame.assign(m=[None] + ["a"] * 11)
        )
    assert dropped.response_values.shape == (11,)
    # A categorical response gives every free category its own coefficients.
    categorical = fit(
        "g1 ~ (1 | mm(g2, g3))",
        data=frame,
        family="categorical",
        method="svi",
        num_steps=1,
    )
    assert any(
        name.startswith("dpar_mu") and "_z_mmg2g3_" in name
        for name in categorical.draws()
    )


def _frame(rows: int = 36) -> pd.DataFrame:
    generator = np.random.default_rng(13)
    frame = pd.DataFrame(
        {
            "g1": generator.choice(list("abcdef"), rows),
            "g2": generator.choice(list("abcdef"), rows),
            "x1": generator.normal(size=rows),
            "x2": generator.normal(size=rows),
            "w1": generator.uniform(0.5, 2.0, rows),
            "w2": generator.uniform(0.5, 2.0, rows),
        }
    )
    frame["y"] = 0.5 * frame["x1"] + generator.normal(scale=0.5, size=rows)
    return frame


FORMULA = "y ~ x1 + (1 + mmc(x1, x2) | mm(g1, g2, weights = cbind(w1, w2)))"


def _fresh() -> pd.DataFrame:
    return pd.DataFrame(
        {
            "g1": ["a", "c", "f"],
            "g2": ["b", "a", "d"],
            "x1": [0.2, -1.0, 0.5],
            "x2": [1.0, 0.0, -0.3],
            "w1": [1.0, 2.0, 1.0],
            "w2": [1.0, 1.0, 3.0],
        }
    )


@pytest.mark.parametrize("method", ["svi", "hmc", "nuts"])
def test_every_inference_method_predicts_fresh_rows(method):
    fitted = _fit_with(method, FORMULA, _frame())
    fresh = _fresh()
    for draws in (
        fitted.posterior_linpred(new_data=fresh, num_samples=2, seed=5),
        fitted.posterior_epred(new_data=fresh, num_samples=2, seed=5),
        fitted.posterior_predict(new_data=fresh, num_samples=2, seed=5),
        *fitted.log_likelihood(
            new_data=fresh.assign(y=[0.1, -0.4, 0.3]), num_samples=2, seed=5
        ).values(),
    ):
        assert draws.shape[-1] == 3 and torch.isfinite(draws).all()


def test_fresh_rows_reproduce_the_hand_assembled_member_sum():
    frame = _frame()
    # Independent coefficients are sigma * z, so draws give them directly.
    independent = FORMULA.replace(" | mm(", " || mm(")
    fitted = fit(independent, data=frame, method="svi", num_steps=3, seed=3)
    fresh = _fresh()
    linpred = fitted.posterior_linpred(new_data=fresh, num_samples=3, seed=4)
    draws = fitted.draws(num_samples=3, seed=4)
    levels = fitted.formula.group_levels["mmg1g2"]
    position = {label: index for index, label in enumerate(levels)}
    weights = fresh[["w1", "w2"]].to_numpy() / fresh[["w1", "w2"]].to_numpy().sum(
        1, keepdims=True
    )
    covariates = {
        "Intercept": np.ones((3, 2)),
        "mmc(x1, x2)": fresh[["x1", "x2"]].to_numpy(),
    }
    expected = draws["intercept"].double()[..., None] + draws["beta_x1"].double()[
        ..., None
    ] * torch.tensor(fresh["x1"].to_numpy(dtype=float))
    for slope in ("Intercept", "mmc(x1, x2)"):
        name = f"mmg1g2_{_qvr_name(slope)}"
        effects = (
            draws[f"sigma_{name}"].double()[..., None] * draws[f"z_{name}"].double()
        )
        for k, column in enumerate(("g1", "g2")):
            codes = [position[value] for value in fresh[column]]
            expected = expected + effects[..., codes] * torch.as_tensor(
                weights[:, k] * covariates[slope][:, k]
            )
    torch.testing.assert_close(linpred, expected)


def test_new_member_levels_use_the_shared_policies():
    fitted = fit(FORMULA, data=_frame(), method="svi", num_steps=2, seed=4)
    fresh = _fresh().assign(g2=["new", "a", "other"])
    with pytest.raises(ValueError, match="allow_new_levels"):
        fitted.posterior_epred(new_data=fresh, num_samples=1)
    for policy in ("uncertainty", "gaussian", "old_levels"):
        draws = fitted.posterior_epred(
            new_data=fresh,
            num_samples=2,
            seed=1,
            allow_new_levels=True,
            sample_new_levels=policy,
        )
        assert draws.shape[-1] == 3 and torch.isfinite(draws).all()
    without = fitted.posterior_epred(
        new_data=fresh, num_samples=2, seed=1, re_formula="~0"
    )
    assert torch.isfinite(without).all()


def test_training_rows_as_new_data_reproduce_the_training_predictor():
    frame = _frame()
    fitted = fit(FORMULA, data=frame, method="svi", num_steps=2, seed=3)
    torch.testing.assert_close(
        fitted.posterior_linpred(new_data=frame, num_samples=3, seed=4),
        fitted.posterior_linpred(num_samples=3, seed=4),
    )


def test_priors_select_the_brms_group_label():
    frame = _frame()
    priors = get_prior(FORMULA, data=frame)
    assert {
        "sigma_mmg1g2_Intercept",
        "sigma_mmg1g2_mmc_x1_x2",
        "cor_mmg1g2",
    } <= priors.keys()
    selected = get_prior(
        FORMULA,
        data=frame,
        priors=PriorSpec(distribution="HalfNormal(0.5)", class_="sd", group="mmg1g2"),
    )
    assert selected["sigma_mmg1g2_Intercept"] == "HalfNormal(scale=0.5)"


def test_update_kfold_and_artifact_round_trip(tmp_path, monkeypatch):
    frame = _frame()
    fitted = fit(FORMULA, data=frame, method="svi", num_steps=1, seed=7)
    refit = fitted.update(data=frame.iloc[:24].reset_index(drop=True))
    assert refit.formula.response_values.shape == (24,)
    recipe = fitted.refit_recipe
    assert recipe is not None
    callback = refit_callback(
        recipe,
        lambda data, rows: pd.DataFrame(data).iloc[list(rows)].copy(),
        lambda refitted, held, seed: refitted.log_likelihood(
            new_data=held, num_samples=2, seed=seed, allow_new_levels=True
        ),
        method_factory=lambda settings, seed: {**settings, "seed": seed},
    )
    result = cross_validate(
        FoldPlan(assignments=tuple((i // 3) % 2 for i in range(36)), seed=1), callback
    )
    assert result.complete and result.log_predictive_density.shape == (36,)
    fresh = _fresh()
    expected = fitted.posterior_epred(new_data=fresh, num_samples=2, seed=9)
    path = tmp_path / "membership.qfit"
    save_fit(fitted, path)

    def forbid(*args, **kwargs):
        raise AssertionError("restoring a membership fit must not run inference")

    monkeypatch.setattr(api, "_run_inference", forbid)
    restored = _restored(path)
    assert restored.formula.grouping == fitted.formula.grouping
    torch.testing.assert_close(
        restored.posterior_epred(new_data=fresh, num_samples=2, seed=9), expected
    )


def test_lens_round_trip_and_distributional_membership():
    frame = _frame()
    formula = formula_from_data(FORMULA, frame)
    lens = FormulaToQVRModule(families["gaussian"])
    module, complement = lens.forward(formula)
    assert lens.backward(module, complement) == formula
    fitted = fit(
        "y ~ x1",
        data=frame,
        distributional={"sigma": "~ 1 + (1 | mm(g1, g2))"},
        method="svi",
        num_steps=2,
        seed=6,
    )
    assert torch.isfinite(
        fitted.posterior_epred(new_data=_fresh(), num_samples=2, seed=1)
    ).all()
